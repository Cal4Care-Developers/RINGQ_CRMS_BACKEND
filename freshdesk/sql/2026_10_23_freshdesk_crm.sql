-- Freshdesk CRM integration -- PostgreSQL (database: ringq)
-- Additive only: creates three NEW tables. Touches no existing table or data
-- (reads q_ringq_cdr, v_domains and v_extensions at runtime, never alters them).
-- Safe to run more than once (IF NOT EXISTS everywhere).
-- Run as the DB owner:  psql -U <owner> -d ringq -v ON_ERROR_STOP=1 -f 2026_10_23_freshdesk_crm.sql
-- Roll back:            2026_10_23_freshdesk_crm_rollback.sql

BEGIN;

-- One row per tenant. The Freshdesk API key is AES-256-GCM encrypted by the
-- app (key derived from application.cryptSalt, never stored in the DB).
CREATE TABLE IF NOT EXISTS public.q_freshdesk_config (
    domain_uuid           uuid PRIMARY KEY,
    enabled               boolean      NOT NULL DEFAULT false,
    fd_domain             varchar(120) NULL,          -- e.g. cal4care.freshdesk.com
    api_key_enc           text         NULL,          -- "v1:" || base64(iv|tag|ciphertext); NULL after disconnect
    key_last4             varchar(8)   NULL,          -- shown masked to admins ("••••abcd")
    fd_agent_id           varchar(32)  NULL,          -- Freshdesk agent the API key belongs to (GET agents/me)
    fd_agent_name         varchar(120) NULL,
    fd_account_name       varchar(120) NULL,
    ticket_field_warnings jsonb        NULL,          -- custom ticket fields Freshdesk requires (may block ticket creation)
    settings              jsonb        NOT NULL DEFAULT '{}'::jsonb,
    connection_status     varchar(20)  NOT NULL DEFAULT 'not_configured'
                          CHECK (connection_status IN ('not_configured', 'connected', 'error', 'disconnected')),
    last_tested_at        timestamptz  NULL,
    last_sync_at          timestamptz  NULL,
    last_error            varchar(500) NULL,
    link_salt             varchar(32)  NOT NULL,      -- rotating salt; changing it revokes every recording link
    updated_by            varchar(64)  NULL,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now()
);

-- One row per RingQ call (per tenant). local_call_id is generated by the
-- dialer when the call starts; the unique key makes every retried event
-- idempotent, and the partial unique index guarantees one Freshdesk ticket per call.
CREATE TABLE IF NOT EXISTS public.q_freshdesk_call_journals (
    journal_uuid           uuid PRIMARY KEY,
    domain_uuid            uuid         NOT NULL,
    local_call_id          varchar(64)  NOT NULL,
    user_uuid              varchar(64)  NULL,
    agent_extension        varchar(32)  NULL,
    agent_name             varchar(120) NULL,
    call_direction         varchar(8)   NOT NULL CHECK (call_direction IN ('inbound', 'outbound')),
    call_origin            varchar(16)  NOT NULL DEFAULT 'dialer' CHECK (call_origin IN ('dialer', 'freshdesk_cti')),
    caller_number          varchar(32)  NULL,
    destination_number     varchar(32)  NULL,
    call_status            varchar(12)  NOT NULL DEFAULT 'ringing'
                           CHECK (call_status IN ('ringing', 'answered', 'completed', 'missed', 'rejected', 'busy', 'no_answer', 'failed')),
    started_at             timestamptz  NOT NULL DEFAULT now(),
    answered_at            timestamptz  NULL,
    ended_at               timestamptz  NULL,
    duration               integer      NOT NULL DEFAULT 0,   -- seconds, start -> end
    talk_duration          integer      NOT NULL DEFAULT 0,   -- seconds, answered -> end (measured by the dialer)
    notes                  text         NULL,                 -- agent notes
    disposition            varchar(40)  NULL,                 -- agent-chosen call outcome
    notes_dirty            boolean      NOT NULL DEFAULT false, -- notes changed after the ticket was created
    notes_note_id          varchar(32)  NULL,                 -- Freshdesk note holding the agent notes
    freshdesk_contact_id   varchar(32)  NULL,
    freshdesk_ticket_id    varchar(32)  NULL,
    create_attempted_at    timestamptz  NULL,                 -- set before POST /tickets: crash recovery looks the ticket up
    xml_cdr_uuid           uuid         NULL,                 -- q_ringq_cdr row holding the recording
    recording_status       varchar(12)  NOT NULL DEFAULT 'none'
                           CHECK (recording_status IN ('none', 'waiting', 'linked', 'uploaded', 'link_only', 'unavailable')),
    recording_note_id      varchar(32)  NULL,                 -- Freshdesk note carrying the recording
    recording_attempted_at timestamptz  NULL,                 -- set before the upload: crash recovery looks the note up
    sync_status            varchar(10)  NOT NULL DEFAULT 'pending'
                           CHECK (sync_status IN ('pending', 'synced', 'failed', 'skipped')),
    retry_count            integer      NOT NULL DEFAULT 0,
    next_attempt_at        timestamptz  NULL,
    sync_locked_at         timestamptz  NULL,
    synced_at              timestamptz  NULL,
    last_error             varchar(500) NULL,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT q_freshdesk_call_journals_call_uq UNIQUE (domain_uuid, local_call_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS q_freshdesk_call_journals_ticket_uq
    ON public.q_freshdesk_call_journals (domain_uuid, freshdesk_ticket_id) WHERE freshdesk_ticket_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_freshdesk_call_journals_due_idx
    ON public.q_freshdesk_call_journals (next_attempt_at) WHERE next_attempt_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_freshdesk_call_journals_started_idx
    ON public.q_freshdesk_call_journals (domain_uuid, started_at DESC);
CREATE INDEX IF NOT EXISTS q_freshdesk_call_journals_user_idx
    ON public.q_freshdesk_call_journals (domain_uuid, user_uuid, started_at DESC);

-- Dialer tokens for the RingQ dialer inside Freshdesk (CTI app). The Freshdesk
-- window does not send RingQ's (SameSite=Lax) login cookie, so the agent
-- connects the dialer once through a RingQ pop-up, which issues one of these.
-- Only the SHA-256 of the token is stored; tokens expire and can be revoked.
CREATE TABLE IF NOT EXISTS public.q_freshdesk_cti_tokens (
    token_hash    char(64)     PRIMARY KEY,
    domain_uuid   uuid         NOT NULL,
    user_uuid     varchar(64)  NOT NULL,
    extension     varchar(32)  NOT NULL,
    agent_name    varchar(120) NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    last_used_at  timestamptz  NULL,
    expires_at    timestamptz  NOT NULL,
    revoked_at    timestamptz  NULL
);
CREATE INDEX IF NOT EXISTS q_freshdesk_cti_tokens_user_idx
    ON public.q_freshdesk_cti_tokens (domain_uuid, user_uuid);

COMMIT;
