		/**
		 * Resolve a stored timezone to a name DateTimeZone will accept.
		 *
		 * Must stay in step with ReportsController::resolveScheduleReportTimezone(): if the two
		 * disagree, the "Next Run" the panel shows is not the time this worker actually runs.
		 */
		private function resolveScheduleReportTimezone($value, $domainUuid = null) {
			$canonical = $this->canonicalScheduleReportTimezone($value);
			if ($canonical !== null) {
				return $canonical;
			}

			$canonical = $this->canonicalScheduleReportTimezone($this->scheduleReportDomainTimezone($domainUuid));
			if ($canonical !== null) {
				return $canonical;
			}

			$canonical = $this->canonicalScheduleReportTimezone(date_default_timezone_get());

			return $canonical === null ? 'UTC' : $canonical;
		}

		/**
		 * The canonical zone name for $value, or null when DateTimeZone will not accept it.
		 *
		 * The parenthetical suffix is stripped explicitly rather than left to the engine: PHP 7.4
		 * parses "Asia/Shanghai (CST, +0800)" and PHP 8 rejects it, so leaning on that leniency
		 * would break scheduled reports on a PHP upgrade with no change to this code.
		 */
		private function canonicalScheduleReportTimezone($value) {
			if (!is_string($value)) {
				return null;
			}

			$value = trim($value);
			$paren = strpos($value, ' (');
			if ($paren !== false) {
				$value = rtrim(substr($value, 0, $paren));
			}

			if ($value === '') {
				return null;
			}

			try {
				$zone = new \DateTimeZone($value);

				return $zone->getName();
			} catch (\Exception $e) {
				return null;
			}
		}

		private function scheduleReportDomainTimezone($domainUuid) {
			if (empty($domainUuid)) {
				return '';
			}

			$vUserSetting = VUserSettings::findFirst([
				"conditions" => "domain_uuid = :domain_uuid: AND user_setting_subcategory = :user_setting_subcategory:",
				"bind" => [
					"domain_uuid" => $domainUuid,
					"user_setting_subcategory" => "time_zone",
				],
				"bindTypes" => [Column::BIND_PARAM_STR, Column::BIND_PARAM_STR],
			]);

			return $vUserSetting ? (string) $vUserSetting->user_setting_value : '';
		}

		private function normalizeScheduleReportEmails($value) {
			$emails = [];
			$values = is_array($value) ? $value : [$value];
			foreach ($values as $rawValue) {
				$parts = preg_split('/[;,:\s]+/', (string) $rawValue);
				foreach ($parts as $part) {
					$email = strtolower(trim((string) $part));
					if ($email !== '' && filter_var($email, FILTER_VALIDATE_EMAIL) && !in_array($email, $emails, true)) {
						$emails[] = $email;
					}
				}
			}

			return $emails;
		}

		private function resolveScheduleReportRecipients($config, $reportType) {
			$reportRecipients = [];
			if (isset($config['report_recipients']) && is_array($config['report_recipients']) && isset($config['report_recipients'][$reportType])) {
				$reportRecipients = $this->normalizeScheduleReportEmails($config['report_recipients'][$reportType]);
			}

			if (!empty($reportRecipients)) {
				return $reportRecipients;
			}

			$fallbackRecipients = $this->normalizeScheduleReportEmails($config['recipient_email'] ?? null);
			if (!empty($fallbackRecipients)) {
				return $fallbackRecipients;
			}

			return $this->normalizeScheduleReportEmails($config['user_email'] ?? null);
		}

