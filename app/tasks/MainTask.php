			if (!file_exists($path)) {
				echo "⚠ Skipped: $path does not exist.\n";
				continue;
			}

			// Ownership check
			if (isset($target['owner']) && isset($target['group'])) {
				$currentOwner = function_exists('posix_getpwuid') ? posix_getpwuid(fileowner($path))['name'] : '';
				$currentGroup = function_exists('posix_getgrgid') ? posix_getgrgid(filegroup($path))['name'] : '';

				if ($currentOwner !== $target['owner'] || $currentGroup !== $target['group']) {
					$runCommand(sprintf(
						'sudo chown -R %s:%s %s',
						escapeshellarg($target['owner']),
						escapeshellarg($target['group']),
