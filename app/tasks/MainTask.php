	private function resolveCertFqdn(): ?string
	{
		$publicUrl = strtolower(trim((string) $this->config->application->publicUrl));
		if ($this->redis->get('install_mode') === 'mt') {
			return $publicUrl !== '' ? $publicUrl : null;
		}
		$hostname = '/^(?=.{1,253}$)[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$/D';
		$licence = json_decode((string) $this->redis->get('ringq_config'), true);
		$licensed = is_array($licence) ? strtolower(trim((string) ($licence['data']['fqdn'] ?? ''))) : '';
		if ($licensed !== '' && preg_match($hostname, $licensed) === 1 && filter_var($licensed, FILTER_VALIDATE_IP) === false) {
			return $licensed;
		}
		if ($publicUrl === '') {
			return null;
		}
		$exact = VDomains::findFirst([
			'conditions' => 'domain_name = :domain:',
			'bind' => ['domain' => $publicUrl],
			'bindTypes' => [Column::BIND_PARAM_STR],
		]);
		if ($exact) {
			return (string) $exact->domain_name;
		}
		$matches = [];
		foreach (VDomains::find([
			'conditions' => 'domain_name LIKE :domain:',
			'bind' => ['domain' => '%' . $publicUrl . '%'],
			'bindTypes' => [Column::BIND_PARAM_STR],
		]) as $row) {
			$name = strtolower(trim((string) $row->domain_name));
			if (preg_match($hostname, $name) === 1 && filter_var($name, FILTER_VALIDATE_IP) === false) {
				$matches[$name] = true;
			}
		}
		return count($matches) === 1 ? (string) array_key_first($matches) : null;
	}

	public function checkCertsAction() {
		$getLicenseConfig = $this->redis->get('ringq_config');
		$licenseConfig = json_decode($getLicenseConfig, true);

		$contactEmail = 'cm@cal4care.com';
		$installMode = $this->redis->get('install_mode');

		// Determine FQDN, API token, and cert domain based on install mode
		if ($installMode === 'mt') {
			// Multi-tenant: wildcard cert under ringq.cloud
			$sslfqdn = $this->config->application->publicUrl;
			$fqdn = $sslfqdn;
			$certDomain = '*.' . $fqdn;
			$apiToken = 'cfat_RqKQ5dnxdJh0fFtUR2ThJTEZy0MO7peqMCR7xvk8bb1c7ebc';
		} else {
			// Single-tenant: specific cert under ringq.ai
			$fqdn = $this->resolveCertFqdn();
			if ($fqdn === null) {
				echo json_encode(['error' => 'Could not tell which domain the certificate is for (no licensed FQDN and no single matching domain)'], JSON_PRETTY_PRINT);
				return;
			}
			$certDomain = $fqdn;
			$apiToken = 'cfat_RqKQ5dnxdJh0fFtUR2ThJTEZy0MO7peqMCR7xvk8bb1c7ebc';
		}

		// Both modes use /etc/letsencrypt/live/ (certbot)
		$certDir = '/etc/letsencrypt/live/' . $fqdn;
		$certFile = $certDir . '/fullchain.pem';

		// Missing cert dir/file = first-time issuance path. Skip self-heal and
		// expiry-gate, fall straight through to certbot issuance below.
		$needsBootstrap = (!is_dir($certDir) || !file_exists($certFile));

		if (!$needsBootstrap) {
			// Self-heal: rebuild /etc/freeswitch/tls/all.pem if it has the cert chain
			// but no private key. LE renewal occasionally writes fullchain without
			// appending privkey, which breaks WSS-enabled sofia profiles ("Bad
			// WSS.PEM certificate"). Only triggers on the broken state — no-op
			// otherwise — and runs independently of the 7-day expiry gate below.
			$fsAllPem = "/etc/freeswitch/tls/all.pem";
			$lePrivkey = "{$certDir}/privkey.pem";
			if (file_exists($fsAllPem) && file_exists($lePrivkey) &&
				strpos((string) @file_get_contents($fsAllPem), 'PRIVATE KEY') === false) {
				exec("sudo bash -c 'cat " . escapeshellarg($certFile) . " " . escapeshellarg($lePrivkey) . " > /etc/freeswitch/tls/all.pem'");
				exec("sudo chown www-data:www-data /etc/freeswitch/tls/all.pem");
				exec("sudo chmod 640 /etc/freeswitch/tls/all.pem");
				// Same reason as the renewal path below: keep the standalone
				// wss.key in sync so the WSS 7443 bind doesn't fail on restart.
				$wssKey = "/etc/freeswitch/tls/wss.key";
				if (!is_link($wssKey) || @readlink($wssKey) !== 'all.pem') {
					@unlink($wssKey);
					@symlink('all.pem', $wssKey);
				}

				exec("sudo systemctl restart freeswitch");
			}

			// Check certificate expiry
			$opensslOutput = shell_exec("openssl x509 -enddate -noout -in " . escapeshellarg($certFile));
			if (!preg_match('/notAfter=(.*)/', $opensslOutput, $matches)) {
				echo json_encode(['error' => 'Could not parse certificate expiry date'], JSON_PRETTY_PRINT);
				return;
			}

			$expiryDate = strtotime($matches[1]);
			$currentDate = time();
			$daysUntilExpiry = ($expiryDate - $currentDate) / 86400;

			// Only renew if expiring within 7 days
			if ($daysUntilExpiry > 7) {
				echo json_encode([
					'status' => 'ok',
					'message' => "Certificate is valid. Expires in " . round($daysUntilExpiry) . " days.",
					'expiryDate' => $matches[1]
				], JSON_PRETTY_PRINT);
				return;
			}
		}

		// --- Certificate Issuance/Renewal via Certbot DNS-01 ---
		// certbot PERSISTS this path into /etc/letsencrypt/renewal/<fqdn>.conf and
		// re-reads it on every unattended renewal. Writing it to /tmp and
		// unlinking it after issuance -- what this did before -- left every later
		// `certbot renew` failing with "File not found: /tmp/cloudflare_*.ini".
		// Measured on graylunaplc.ringq.ai 2026-09-11: the timer was enabled and
		// running, the cert was healthy, and `certbot renew --dry-run` reported
		// "All simulated renewals failed" -- it would have failed at its October
		// window with no earlier warning, because the timer SKIPS (and so never
		// touches the credentials) until the cert is actually due. The file must
		// therefore outlive the request that creates it.
		//
		// Staged as www-data (which cannot write /etc/letsencrypt) and installed
		// by root with the mode applied BEFORE the file lands, so the token is
		// never briefly world-readable; it never reaches a command line either.
		$iniPath = SslController::CLOUDFLARE_INI;
		$stage   = (string)tempnam(sys_get_temp_dir(), 'cfini');
		file_put_contents($stage, "dns_cloudflare_api_token = {$apiToken}\n");
		chmod($stage, 0600);
		exec("sudo install -D -o root -g root -m 600 "
			. escapeshellarg($stage) . " " . escapeshellarg($iniPath));
		@unlink($stage);

		$certbotCommand = "sudo certbot certonly " .
			"--dns-cloudflare " .
			"--dns-cloudflare-credentials {$iniPath} " .
			"--non-interactive " .
			"--agree-tos " .
			"--email " . escapeshellarg($contactEmail) . " " .
			($needsBootstrap ? "" : "--force-renewal ") .
			"-d " . escapeshellarg($certDomain);

		$output = [];
		exec($certbotCommand . ' 2>&1', $output, $result);

		// Deliberately NOT unlinked: certbot needs it again at every renewal.

		// --- Copy WSS certs to FreeSWITCH ---
		// NOTE: wss.pem is a symlink to all.pem; all.pem must contain fullchain + privkey combined.
		$fullchain = "{$certDir}/fullchain.pem";
		$privkey   = "{$certDir}/privkey.pem";
		$certPem   = "{$certDir}/cert.pem";
		$chainPem  = "{$certDir}/chain.pem";
		$certPath  = "/etc/freeswitch/tls";

		if (file_exists($fullchain) && file_exists($privkey)) {
			// Rebuild all.pem = fullchain + privkey (what FreeSWITCH actually reads via wss.pem symlink)
			exec("sudo bash -c 'cat " . escapeshellarg($fullchain) . " " . escapeshellarg($privkey) . " > {$certPath}/all.pem'");
			exec("sudo cp " . escapeshellarg($fullchain) . " {$certPath}/fullchain.pem");
			exec("sudo cp " . escapeshellarg($privkey)   . " {$certPath}/privkey.pem");
			if (file_exists($certPem))  exec("sudo cp " . escapeshellarg($certPem)  . " {$certPath}/cert.pem");
			if (file_exists($chainPem)) exec("sudo cp " . escapeshellarg($chainPem) . " {$certPath}/chain.pem");
			exec("sudo chown www-data:www-data {$certPath}/all.pem {$certPath}/fullchain.pem {$certPath}/privkey.pem {$certPath}/cert.pem {$certPath}/chain.pem");
			exec("sudo chmod 640 {$certPath}/privkey.pem");
			exec("sudo chmod 644 {$certPath}/all.pem {$certPath}/fullchain.pem {$certPath}/cert.pem {$certPath}/chain.pem");

			// The WSS (7443) transport loads wss.pem + wss.key as SEPARATE files.
			// setup.php ships wss.key as a standalone copy of privkey.pem, and the
			// rebuild above never refreshes it — so once the cert rotates, wss.key
			// no longer matches and the internal profile's SIP UA fails to create
			// ("Invalid Profile!") on the freeswitch restart below, while all.pem/
			// wss.pem stay correct. Relink wss.key -> all.pem so it always tracks
			// the renewed key. No sudo: the tls dir is www-data-writable and the
			// sudoers whitelist has no ln/rm entry (matches SslController).
			$wssKey = "{$certPath}/wss.key";
			if (!is_link($wssKey) || @readlink($wssKey) !== 'all.pem') {
				@unlink($wssKey);
				@symlink('all.pem', $wssKey);
			}
		}

		// --- Restart services ---
		exec("sudo systemctl restart nginx");
		exec("sudo systemctl restart freeswitch");
		exec("sudo pm2 restart all");

		// --- Send email notification on success ---
		if ($result === 0) {
			$newExpiryOutput = shell_exec("openssl x509 -enddate -noout -in " . escapeshellarg($certFile));
			preg_match('/notAfter=(.*)/', $newExpiryOutput, $newMatches);

			$emailSender = new Library\Email();
			$emailSender->send($licenseConfig['data']['company_email'], "SSL Certificate Renewal", "", [
				"type" => 14,
				"fqdn" => $licenseConfig['data']['fqdn'],
				"date" => $newMatches[1] ?? 'Unknown'
			], $licenseConfig);
		}
	}

	public function webinarRemindersAction() {
        // Check for migration
        if (!$this->redis->exists("webinar_ids_migrated")) {
            $existingKeys = $this->redis->keys("webinar_details:*");
            foreach ($existingKeys as $key) {
                $parts = explode(":", $key);
                if (count($parts) === 2) {
                    $this->redis->sadd("webinar_ids", $parts[1]);
                }
            }
            $this->redis->set("webinar_ids_migrated", 1);
        }

        $webinarIds = $this->redis->smembers("webinar_ids");
        $keys = [];
        foreach ($webinarIds as $id) {
            $keys[] = "webinar_details:" . $id;
        }
        $now = time();

        foreach ($keys as $key) {
            $webinarJson = $this->redis->get($key);
            if (!$webinarJson) continue;

            $webinar = json_decode($webinarJson, true);
            if (!isset($webinar['id'])) continue;

            // Check if reminder enabled
            if (empty($webinar['reminderEnabled']) || $webinar['reminderEnabled'] === 'false' || !$webinar['reminderEnabled']) {
                continue;
            }

            // Parse Date/Time
            $date = $webinar['date'] ?? '';
            $time = $webinar['time'] ?? '';
            if (!$date || !$time) continue;

            $datePart = explode('T', $date)[0];
            $startTime = strtotime("$datePart $time");

            if (!$startTime) continue;

            // Parse Reminder Time
            $reminderTimeStr = $webinar['reminderTime'] ?? '15 mins before';
            $secondsBefore = 900; // default 15 min

            if (preg_match('/(\d+)\s*min/', $reminderTimeStr, $matches)) {
                $secondsBefore = intval($matches[1]) * 60;
            } elseif (preg_match('/(\d+)\s*hr/', $reminderTimeStr, $matches)) {
                $secondsBefore = intval($matches[1]) * 3600;
            } elseif (preg_match('/(\d+)\s*day/', $reminderTimeStr, $matches)) {
                $secondsBefore = intval($matches[1]) * 86400;
            }

            $reminderTimestamp = $startTime - $secondsBefore;

            // Check if it is time to send reminder (within window and not passed start time)
            if ($now >= $reminderTimestamp && $now < $startTime) {
                $sentKey = "webinar_reminder_sent:" . $webinar['id'];
                if (!$this->redis->exists($sentKey)) {
					$participantsKey = "webinar_participants:" . $webinar['id'];

					$participants = $this->redis->lrange($participantsKey, 0, -1);
					foreach ($participants as $pJson) {
						$p = json_decode($pJson, true);
						if (isset($p['email'])) {
							$this->redis->lpush("email_queue", json_encode([
								"type" => "webinar_reminder",
								"webinarId" => $webinar['id'],
								"data" => $p
							]));
						}
					}

                    // Mark as sent and expire after 2 days
                    $this->redis->set($sentKey, 1);
                    $this->redis->expire($sentKey, 172800);
                }
            }
        }
    }

