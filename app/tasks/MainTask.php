					continue;
				}
				foreach ($g['recipients'] as $recipient) {
					$byRecipient[$recipient][] = $i;
				}
			}

			$customName = null;
			if (!empty($config['domain_uuid'])) {
				$cachedLicense = $this->redis->get("api_cache:licensecheckuser:" . $config['domain_uuid']);
				if ($cachedLicense) {
					$cachedLicense = json_decode($cachedLicense, true);
					$customName = $cachedLicense["companyNameWhiteLabel"] ?? null;
				}
			}

			$fqdn = $licenseConfig['data']['fqdn'] ?? '';
			$periodText = $this->scheduleReportPeriodText($frequency, $periodStart, $periodEnd, $timezone);
			$time = $config['time'] ?? '';
			$schedule = $frequency;
			if ($frequency === 'Weekly') {
				$schedule .= ', ' . ($config['day_of_week'] ?? 'Monday');
			} elseif ($frequency === 'Monthly') {
				$schedule .= ', day ' . ($config['day_of_month'] ?? '1');
			}
			if ($time !== '') {
				$schedule .= ' at ' . $time;
			}
			$prefix = (!empty($customName) && $customName !== 'RingQ') ? $customName . ': ' : '';

			$email = new Library\Email();
			foreach ($byRecipient as $recipient => $indexes) {
				$reports = [];
				$files = [];
				foreach ($indexes as $i) {
					$g = $generated[$i];
					$label = $g['type'] . ($g['all_time'] ? ' (all time)' : '');
					$reports[] = ['label' => $label, 'filename' => $g['filename'], 'rows' => $g['rows']];
					$files[] = ['path' => "/var/www/ringq/cache/" . $g['file'], 'filename' => $g['filename']];
				}
				if (count($reports) === 1) {
					$title = $generated[$indexes[0]]['type'] . ' report';
				} else {
					$title = 'Scheduled reports';
				}
				$subject = $prefix . $title . ' - ' . $frequency . ' - ' . $periodText;
				try {
					echo "  - Sending " . count($files) . " report(s) to $recipient\n";
					$email->send($recipient, $subject, "email attachment", [
						"type" => "scheduledreport",
