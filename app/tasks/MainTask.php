					            }
					            break;
					        }
					    }
					}
					if (!empty($qCallBehavior->simultaneous_destination_enabled)) {
						$simultaneousDestinationEnabled = explode(",", $qCallBehavior->simultaneous_destination_enabled);
					}
					if (!empty($qCallBehavior->simultaneous_destination_enabled2)) {
