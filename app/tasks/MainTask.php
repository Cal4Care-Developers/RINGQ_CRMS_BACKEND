		private function timeToSeconds($timeString) {
		    $timestamp = strtotime($timeString);
	    $hours = (int)date('H', $timestamp);
	    $minutes = (int)date('i', $timestamp);
	    $seconds = (int)date('s', $timestamp);
	    return ($hours * 3600) + ($minutes * 60) + $seconds;
	}

	private function secondsToTime($seconds) {
	  $t = round($seconds);
	  return sprintf('%02d:%02d:%02d', $t/3600, floor($t/60)%60, $t%60);
	}

	private function secondsToHMS($seconds) {
	    $hours = floor($seconds / 3600);
	    $minutes = floor(($seconds % 3600) / 60);
	    $seconds = $seconds % 60;

	    return sprintf("%02d:%02d:%02d", $hours, $minutes, $seconds);
	}


	/**
	 * Daily storage retention. Reads enabled rows from q_storage_retention and
	 * deletes files older than the configured age. Tenant-scoped categories
	 * (recordings/voicemail) act on the domain's own /<domain_name> subdir so a
	 * purge can never cross tenants; server-global categories (logs/captures/…)
	 * run once per box. Logs remove rotated artefacts only. See
	 * docs/PLAN-storage-retention.md.
	 */
	public function storageRetentionAction() {
		if ($this->redis->exists('lock:storageRetention')) {
			return;
		}
		// predis rejects the array-options form of SET; use SETEX (proven across
		// this codebase). The exists-check above covers the dedup for a daily job.
		$this->redis->setex('lock:storageRetention', 3600, time());
		@set_time_limit(0);
		try {
			// (Audit log retention is count-based — enforced at write time in
			// ControllerBase::enforceAuditRetention, not by this daily job.)
			require_once "/var/www/ringq/app/library/Storage.php";
			$lib = new \Library\Storage();
			$cats = $lib->categories();
			$globalsDone = [];

			$vDomains = VDomains::find(["conditions" => "domain_enabled = true"]);
			foreach ($vDomains as $vDomain) {
				$domainUuid = $vDomain->domain_uuid;
				$domainName = $vDomain->domain_name;

				try {
					$rows = $this->db->fetchAll(
						"SELECT id, category, scope, retention_days, archive FROM q_storage_retention
						   WHERE domain_uuid = :uuid AND enabled = 1",
						\Phalcon\Db\Enum::FETCH_ASSOC,
						["uuid" => $domainUuid]
					);
				} catch (\Throwable $e) {
					continue; // table may not exist yet on a fresh box
				}

				// Cap how many files a single category archives per nightly run, so a
				// first-time archive of a huge tree doesn't run for hours; the rest
				// is picked up on subsequent nights. Plain deletes are uncapped.
				$archiveCap = 2000;

				foreach ($rows as $row) {
					$key = $row["category"];
					if (!isset($cats[$key]) || empty($cats[$key]["deletable"])) {
						continue;
					}
					$scope   = $cats[$key]["scope"] ?? "global";
					$days    = (int)$row["retention_days"];
					$archive = (int)($row["archive"] ?? 0) === 1;
					$cap     = $archive ? $archiveCap : 0;

					if ($scope === "global") {
						if (isset($globalsDone[$key])) {
							continue; // shared dir already handled this run
						}
						$globalsDone[$key] = true;
						$res = $lib->purge($key, $days, false, null, null, $archive, $cap);
					} else {
						$res = $lib->purge($key, $days, false, $domainName, $domainUuid, $archive, $cap);
					}
					try {
						$this->db->execute(
							"UPDATE q_storage_retention
								SET last_run_at = now(), last_freed_bytes = :freed, last_deleted_files = :files
							  WHERE id = :id",
							[
								"freed" => (int)($res["freedBytes"] ?? 0),
								"files" => (int)($res["deletedFiles"] ?? 0),
								"id"    => $row["id"],
							]
						);
					} catch (\Throwable $e) {
						// best-effort bookkeeping; the delete already happened
					}
					echo date('[H:i:s]') . " storageRetention {$domainName}/{$key}: removed "
						. (int)($res["deletedFiles"] ?? 0) . " files, freed "
						. (int)($res["freedBytes"] ?? 0) . " bytes\n";
				}
			}
		} finally {
			$this->redis->del('lock:storageRetention');
		}
	}

	// Voicemail Transcription using RingQ API
	private function audioToTextAction($basePath, $subdomain, $QRingqCdr = null) {
        try {
            $filePath = '';
            $matchedFiles = glob($basePath . '.*');
            if (!empty($matchedFiles)) {
                $filePath = $matchedFiles[0];
            }

            if (empty($filePath) || !file_exists($filePath)) {
                throw new \Exception("File not found for base path: " . $basePath);
            }

            $transcribeEnabled = $this->redis->get("ai:" . $subdomain . "-transcribeTokenEnabled");
            if (!$transcribeEnabled || $transcribeEnabled == "2") {
                throw new \Exception("AI transcription is disabled for subdomain " . $subdomain);
            }

            $aitranscripttype = $this->redis->get("ai:" . $subdomain . "-aitranscripttype");
