	/**
	 * Spawned by UpdateReadiness::spawn() after every successful update.
	 * Waits until the server can take calls again (or gives up after 3
	 * minutes) and records the outcome once: redis update_ready_last, an
	 * audit entry, and an optional webhook post.
	 */
	public function updatereadyAction($runId = '', $trigger = '', $fromVersion = '', $toVersion = '') {
		require_once __DIR__ . "/../library/ServiceHealth.php";
		require_once __DIR__ . "/../library/UpdateReadiness.php";
		require_once __DIR__ . "/../library/AuditMap.php";

		$progress = [
			"runId" => (string)$runId,
			"trigger" => (string)$trigger,
			"fromVersion" => (string)$fromVersion,
			"toVersion" => (string)$toVersion,
			"startedAt" => date('c'),
			"deadline" => date('c', time() + 190),
		];
		UpdateReadiness::saveProgress($this->redis, $progress + ["state" => "starting", "ready" => false, "checks" => []]);

		// The update has just fired `pm2 restart all`; give it a head start
		// so the first pass isn't guaranteed to fail.
		sleep(10);
		$deadline = time() + 180;
		do {
			$result = UpdateReadiness::check($this->redis, (string)$toVersion);
			if ($result['ready']) break;
			UpdateReadiness::saveProgress($this->redis, $progress + ["state" => "checking", "ready" => false, "checks" => $result['checks']]);
			sleep(5);
		} while (time() < $deadline);

		$message = UpdateReadiness::message($result, (string)$toVersion, ServiceHealth::hostname());
		$record = [
			"runId" => (string)$runId,
			"trigger" => (string)$trigger,
			"fromVersion" => (string)$fromVersion,
			"toVersion" => (string)$toVersion,
			"ready" => $result['ready'],
			"checks" => $result['checks'],
			"message" => $message,
			"at" => date('c'),
		];
		try {
			$this->redis->setex(UpdateReadiness::LAST_KEY, 30 * 86400, json_encode($record));
		} catch (\Throwable $e) {
			error_log("updateready redis: " . $e->getMessage());
		}
		UpdateReadiness::saveProgress($this->redis, $record + ["state" => "done", "startedAt" => $progress["startedAt"]]);

		try {
			$config = json_decode((string)$this->redis->get("ringq_config"), true);
			$fqdn = is_array($config) ? ($config["data"]["fqdn"] ?? "") : "";
			AuditMap::insert($this->db, [
				"domain_uuid" => AuditMap::domainUuidFor($this->db, $fqdn),
				"username" => "update-check",
				"user_fullname" => "Post-update check",
				"user_email" => null,
				"ip_address" => "",
				"user_agent" => "cli.php main updateready",
				"feature" => "system-update",
				"action" => $result['ready'] ? "update-ready" : "update-not-ready",
				"entity" => (string)$toVersion !== '' ? (string)$toVersion : "latest",
				"result" => $result['ready'] ? "success" : "error",
				"metadata" => AuditMap::encodeMetadata(AuditMap::redact([
					"trigger" => (string)$trigger,
					"runId" => (string)$runId,
					"fromVersion" => (string)$fromVersion,
					"toVersion" => (string)$toVersion,
					"message" => $message,
					"checks" => $result['checks'],
				])),
			]);
		} catch (\Throwable $e) {
			error_log("updateready audit: " . $e->getMessage());
		}

		// Optional chat webhook (Slack, Teams and Google Chat all accept
		// {"text": ...}), set per server with `redis-cli set update_ready_webhook <url>`.
		$webhook = (string)$this->redis->get(UpdateReadiness::WEBHOOK_KEY);
		if (preg_match('#^https://#', $webhook)) {
			$ch = curl_init($webhook);
			curl_setopt_array($ch, [
				CURLOPT_POST => true,
				CURLOPT_POSTFIELDS => json_encode(["text" => $message]),
				CURLOPT_HTTPHEADER => ["Content-Type: application/json"],
				CURLOPT_RETURNTRANSFER => true,
				CURLOPT_TIMEOUT => 10,
			]);
			curl_exec($ch);
			curl_close($ch);
		}

		echo $message . PHP_EOL;
	}

	public function autosipguardAction() {
