							}
						} else {
							echo "Invalid report data popped: " . substr($reportJson, 0, 50) . "...\n";
						}
					}
					echo "Email sending completed.\n";
				}
			} finally {
				$this->redis->del("lock:scheduled_reports_processing");
			}
		}
