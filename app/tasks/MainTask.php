						"link" => $fqdn !== '' ? "https://" . $fqdn . "/cloudapp/" : '',
					], $licenseConfig, $customName);
				} catch (\Exception $e) {
					foreach ($indexes as $i) {
						$results[$i]['errors'][] = $recipient . ": " . $e->getMessage();
					}
				}
			}

			foreach ($generated as $i => $g) {
				@unlink("/var/www/ringq/cache/" . $g['file']);
				if (!empty($results[$i]['errors'])) {
					$results[$i]['status'] = 'failed';
					$results[$i]['error'] = implode("; ", $results[$i]['errors']);
				}
				unset($results[$i]['errors']);
			}

			return $results;
		}

		/** "13 Oct 2026" for a daily run, "6 Oct - 12 Oct 2026" for a range. */
		private function scheduleReportPeriodText($frequency, $periodStart, $periodEnd, $timezone) {
			try {
				$tz = new \DateTimeZone($timezone);
			} catch (\Exception $e) {
				$tz = new \DateTimeZone('UTC');
			}
			$start = (new \DateTime('@' . (int) $periodStart))->setTimezone($tz);
			$end = (new \DateTime('@' . (int) $periodEnd))->setTimezone($tz);
			if ($start->format('Y-m-d') === $end->format('Y-m-d')) {
				return $start->format('j M Y');
			}
			if ($frequency === 'Monthly' && $start->format('j') === '1' && $start->format('Y-m') === $end->format('Y-m')) {
				return $start->format('F Y');
			}
			return $start->format($start->format('Y') === $end->format('Y') ? 'j M' : 'j M Y') . ' - ' . $end->format('j M Y');
		}

		/** Call-Logs_2026-10-13.csv, Call-Logs_2026-10-06_to_2026-10-12.csv, Call-Logs_2026-09.csv, Call-Logs_all-time_2026-10-13.csv */
		private function scheduleReportFilename($reportType, $frequency, $periodStart, $periodEnd, $timezone, $allTime) {
			try {
				$tz = new \DateTimeZone($timezone);
			} catch (\Exception $e) {
				$tz = new \DateTimeZone('UTC');
			}
			$name = trim(preg_replace('/[^A-Za-z0-9]+/', '-', $reportType), '-');
			if ($allTime) {
				return $name . '_all-time_' . (new \DateTime('now', $tz))->format('Y-m-d') . '.csv';
			}
			$startDt = (new \DateTime('@' . (int) $periodStart))->setTimezone($tz);
			$endDt = (new \DateTime('@' . (int) $periodEnd))->setTimezone($tz);
			if ($frequency === 'Monthly' && $startDt->format('j') === '1' && $startDt->format('Y-m') === $endDt->format('Y-m')) {
				return $name . '_' . $startDt->format('Y-m') . '.csv';
			}
			$start = $startDt->format('Y-m-d');
			$end = $endDt->format('Y-m-d');
			return $name . '_' . ($start === $end ? $start : $start . '_to_' . $end) . '.csv';
		}

		/** Data rows in a generated CSV (header excluded; quoted multi-line fields count once). */
		private function countScheduleReportRows($path) {
			$fp = @fopen($path, 'r');
			if (!$fp) {
				return 0;
			}
			$rows = -1;
			while (($line = fgetcsv($fp)) !== false) {
				if ($line === [null]) {
					continue;
				}
				$rows++;
			}
			fclose($fp);
			return max(0, $rows);
		}

