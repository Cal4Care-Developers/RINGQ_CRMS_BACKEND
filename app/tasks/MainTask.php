				// List down all ip block,
				$output = [];
				$returnCode = 0;
				exec("sudo /sbin/iptables -L -n -v --line-numbers 2>&1", $output, $returnCode);

				if ($returnCode !== 0) {
				    return $this->respondWithError(400, 'Failed to retrieve iptables rules');
				}

				$pattern = '/
				    ^\s*\d+\s+\S+\s+\S+\s+       # line num, pkts, bytes
				    (ACCEPT|DROP|REJECT)\s+      # target
				    \S+\s+\S+\s+\S+\s+\S+\s+     # prot, opt, in, out
				    (\d{1,3}(?:\.\d{1,3}){3}(?:\/\d+)?)\s+ # source
				    (\d{1,3}(?:\.\d{1,3}){3}(?:\/\d+)?)    # destination
				/x';

				$allowedIps2 = [];
				$blockedIps2 = [];

				foreach ($output as $line) {
				    $line = trim($line);
				    if (preg_match($pattern, $line, $matches)) {
				        $action      = $matches[1];
				        $srcAddress  = $matches[2];
				        $destination = $matches[3];

				        // Skip "anywhere"
				        if ($srcAddress === "0.0.0.0/0" || $srcAddress === "0.0.0.0") {
				            continue;
				        }

				        if ($action === 'ACCEPT') {
				            $allowedIps2[] = $srcAddress;
				        } else {
				            $blockedIps2[] = $srcAddress;
				        }
				    }
				}
				$allowedIps = [];
				$blockedIps = [];
				$allowedIps2 = array_unique($allowedIps2);
				$blockedIps2 = array_unique($blockedIps2);
				foreach($blockedIps2 as $blockedIpEntry) {
