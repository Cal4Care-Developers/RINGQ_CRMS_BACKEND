	public function systemAction() {
		$system = new System;
		$os = $system->getOs();
		$system2 = new System2();
		$currentMinute = date("i");
		$currentHour   = date("H");
        $minuteIter = (int)$currentMinute - ((int)$currentMinute % 5);
        $minuteIter = str_pad($minuteIter, 2, "0", STR_PAD_LEFT);
        $timeKey = "$currentHour:$minuteIter";

		$getCpuUsage = function() {
			$statLine = file_get_contents('/proc/stat');
			$stats = explode(' ', preg_replace('!\s+!', ' ', trim($statLine)));
			// indexes: 0:cpu, 1:user, 2:nice, 3:system, 4:idle, 5:iowait, 6:irq, 7:softirq

			$user    = $stats[1];
			$nice    = $stats[2];
			$system  = $stats[3];
			$idle    = $stats[4];
			$iowait  = $stats[5];
			$irq     = $stats[6];
			$softirq = $stats[7];

			$total = $user + $nice + $system + $idle + $iowait + $irq + $softirq;
			$idleTotal = $idle + $iowait;

			$lastStats = $this->redis->get('system_last_proc_stat');

			if ($lastStats) {
				$last = json_decode($lastStats, true);
				$totalDelta = $total - $last['total'];
				$idleDelta  = $idleTotal - $last['idle'];

				$usage = 0;
				if ($totalDelta > 0) {
					$usage = ($totalDelta - $idleDelta) / $totalDelta * 100;
				}
			} else {
				$usage = 0;
			}

			$this->redis->set('system_last_proc_stat', json_encode([
				'total' => $total,
				'idle'  => $idleTotal
			]));

			return round($usage, 2);
		};

        /**
         * Helper closure to safely handle Redis operations that might fail due to type mismatch (WRONGTYPE).
         * If WRONGTYPE is detected, the key is deleted and the operation is retried once.
         */
        $redisSafe = function($operation, ...$args) {
            try {
                return call_user_func_array([$this->redis, $operation], $args);
            } catch (\Throwable $e) {
                if (strpos($e->getMessage(), 'WRONGTYPE') !== false) {
                    $key = $args[0];
                    $this->redis->del($key);
                    error_log("Redis WRONGTYPE detected in MainTask for key: $key. Key deleted and operation retried.");
                    return call_user_func_array([$this->redis, $operation], $args);
                }
                throw $e;
            }
        };

		$cpuUsage = $getCpuUsage();

		// Update hourly history every minute (keeps current hour up to date)
		$redisSafe("hset", "systemLoadPercentage", $timeKey, $cpuUsage);
		$redisSafe("hset", "systemLoadSystem", $timeKey, $os->getLoad(0));
		$redisSafe("hset", "systemDiskUsagePercentage", $timeKey, $os->getDiskUsagePercentage());
		$redisSafe("hset", "systemMemTotal", $timeKey, $system2->memTotal());
		$redisSafe("hset", "systemMemUsed", $timeKey, $system2->memUsed());
		$redisSafe("hset", "systemMemFree", $timeKey, $system2->memFree());
		$redisSafe("hset", "systemMemAvailable", $timeKey, $system2->memAvailable());

        // New Hash Population for API Compatibility
        $redisSafe("hset", "systemLoadPercentage2", $timeKey, $cpuUsage);
        $redisSafe("hset", "systemDiskUsagePercentageHistory", $timeKey, $os->getDiskUsagePercentage());

        $memTotal = $system2->memTotal();
        $memFree = $system2->memFree();
        $memAvailable = $system2->memAvailable();
        // Use Available memory for more accurate "used" calculation (Used = Total - Available)
        // This accounts for cache/buffers that are reclaimable, matching the dashboard indicator.
        $memMetric = ($memAvailable !== null && $memAvailable > 0) ? $memAvailable : $memFree;

        $memUsagePercentage = 0;
        if ($memTotal > 0) {
            $memUsagePercentage = ($memTotal - $memMetric) / $memTotal * 100;
        }
        $redisSafe("hset", "systemMemUsagePercentageHistory", $timeKey, round($memUsagePercentage, 2));

		if ($currentMinute === "00" || $currentMinute === "0") {
			$fields = $redisSafe("hkeys", "systemLoadPercentage");
			sort($fields);
			if (count($fields) > 288) {
			    $extra = array_slice($fields, 0, count($fields) - 288);
			    foreach ($extra as $f) {
			        $redisSafe("hdel", "systemLoadPercentage", $f);
			        $redisSafe("hdel", "systemLoadSystem", $f);
			        $redisSafe("hdel", "systemDiskUsagePercentage", $f);
			        $redisSafe("hdel", "systemCoreCount", $f);
			        $redisSafe("hdel", "systemMemTotal", $f);
			        $redisSafe("hdel", "systemMemUsed", $f);
			        $redisSafe("hdel", "systemMemFree", $f);
			        $redisSafe("hdel", "systemMemAvailable", $f);
			        $redisSafe("hdel", "systemLoadPercentage2", $f);
			        $redisSafe("hdel", "systemMemUsagePercentageHistory", $f);
			        $redisSafe("hdel", "systemDiskUsagePercentageHistory", $f);
			    }
			}
		}
		$redisSafe("rpush", "systemLoadPercentage2_List", $cpuUsage);
		$redisSafe("rpush", "systemLoadSystem2", $os->getLoad(0));
		$redisSafe("rpush", "systemDiskUsagePercentage2", $os->getDiskUsagePercentage());
		$redisSafe("rpush", "systemMemTotal2", $system2->memTotal());
		$redisSafe("rpush", "systemMemUsed2", $system2->memUsed());
		$redisSafe("rpush", "systemMemFree2", $system2->memFree());
		$redisSafe("rpush", "systemMemAvailable2", $system2->memAvailable());
		$redisSafe("ltrim", "systemLoadPercentage2_List", -100, -1);
		$redisSafe("ltrim", "systemLoadSystem2", -100, -1);
		$redisSafe("ltrim", "systemDiskUsagePercentage2", -100, -1);
		$redisSafe("ltrim", "systemMemTotal2", -100, -1);
		$redisSafe("ltrim", "systemMemUsed2", -100, -1);
		$redisSafe("ltrim", "systemMemFree2", -100, -1);
		$redisSafe("ltrim", "systemMemAvailable2", -100, -1);
		$this->redis->set("systemCoreCount", $os->getCoreCount());
		$totalSpace = disk_total_space("/");
		$totalSpaceGB = $totalSpace / (1024 * 1024 * 1024);
		$this->redis->set("totalSpaceGB", $totalSpaceGB);
		$totalSpaceGB = $this->redis->get("totalSpaceGB");
        if ((int)$currentMinute % 5 === 0) {
            $average = function ($key) {
                $values = $this->redis->lrange($key, 0, -1);
                return empty($values) ? null : array_sum($values) / count($values);
            };
            $this->sendSystemUsageAlerts(
                $average("systemLoadPercentage2_List"),
                $average("systemDiskUsagePercentage2"),
                $average("systemMemTotal2"),
                $average("systemMemUsed2"),
                $average("systemMemAvailable2")
            );
        }
    }

    /** Send resource alerts with each tenant's own settings and cooldown. */
    private function sendSystemUsageAlerts($cpu, $disk, $memTotal, $memUsed, $memAvailable)
    {
        // Match the dashboard: reclaimable cache is available memory.
        $ram = null;
        if ($memTotal > 0) {
            $used = $memAvailable > 0 ? $memTotal - $memAvailable : $memUsed;
            if ($used !== null) {
                $ram = round($used / $memTotal * 100, 2);
            }
        }
        $usage = ['cpu' => $cpu, 'ram' => $ram, 'disk_space' => $disk];
        $labels = ['cpu' => 'CPU', 'ram' => 'RAM', 'disk_space' => 'Disk'];
        $licenseConfig = json_decode((string)$this->redis->get('ringq_config'), true);
        $hostname = (string)($licenseConfig['data']['fqdn'] ?? '') ?: gethostname();
        $email = new Library\Email();
        foreach (QEmailNotifications::find() as $notification) {
            $exceeded = [];
            foreach ($usage as $metric => $value) {
                $threshold = $notification->{$metric . '_percentage'};
                if ($notification->{$metric} == 1 && $value !== null
                    && is_numeric($threshold) && $threshold >= 0 && $threshold <= 100
                    && $value >= (float)$threshold) {
                    $exceeded[] = $labels[$metric] . ' ' . round($value) . '%';
                }
            }
            if (!$exceeded) {
                continue;
            }
            $subject = '[' . $hostname . '] System usage alert: ' . implode(', ', $exceeded);
            $recipients = array_unique(array_map('trim', explode(',', $notification->emails ?? '')));
            $domainUuid = $notification->domain_uuid;
            $cachedLicense = json_decode((string)$this->redis->get('api_cache:licensecheckuser:' . $domainUuid), true);
            $customName = $cachedLicense['companyNameWhiteLabel'] ?? 'RingQ';
            foreach ($recipients as $recipient) {
                if (!filter_var($recipient, FILTER_VALIDATE_EMAIL)) {
                    continue;
                }
                $cooldownKey = 'systemEmail-' . $domainUuid . '-' . $recipient;
                if ($this->redis->exists($cooldownKey)) {
                    continue;
                }
                // Sampling jobs can overlap; keep only one send in flight.
                $lockKey = $cooldownKey . ':sending';
                if (!$this->redis->set($lockKey, 1, 'EX', 120, 'NX')) {
                    continue;
                }
                try {
                    if ($this->redis->exists($cooldownKey)) {
                        continue;
                    }
                    $result = $email->send($recipient, $subject, 'system', [
                        'type' => 12,
                        'hostname' => $hostname,
                        'unix' => time(),
                        'cpu' => $cpu,
                        'cpuPercentage' => $notification->cpu_percentage,
                        'cpuEnabled' => $notification->cpu == 1,
                        'ram' => $ram,
                        'ramPercentage' => $notification->ram_percentage,
                        'ramEnabled' => $notification->ram == 1,
                        'disk' => $disk,
                        'diskPercentage' => $notification->disk_space_percentage,
                        'diskEnabled' => $notification->disk_space == 1,
                    ], $licenseConfig, $customName);
                    if (is_array($result) && !empty($result['success'])) {
                        $this->redis->setex($cooldownKey, 3600, 1);
                    } else {
                        error_log('System usage email was not accepted for domain ' . $domainUuid);
                    }
                } catch (\Throwable $error) {
                    // Do not log mail exceptions: they can contain credentials.
                    error_log('System usage email failed for domain ' . $domainUuid . ' (' . get_class($error) . ')');
                } finally {
                    $this->redis->del($lockKey);
                }
            }
        }
    }

