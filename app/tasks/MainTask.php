	public function hotelWakeupCallsAction() {
		// Self-healing schema: idempotent, cheap no-op after the first run.
		try {
			$this->db->execute("CREATE TABLE IF NOT EXISTS public.q_hotel_wakeup_calls (
				hotel_wakeup_call_uuid CHAR(36) PRIMARY KEY,
				domain_uuid CHAR(36) NOT NULL,
				extension_uuid CHAR(36) NOT NULL,
				extension VARCHAR(32) NOT NULL,
				wake_hour INT NOT NULL,
				wake_minute INT NOT NULL,
				wake_ampm VARCHAR(2) NOT NULL,
				wake_datetime TIMESTAMP NOT NULL,
				status INT NOT NULL DEFAULT 1,
				attempts INT NOT NULL DEFAULT 0,
				insert_user CHAR(36),
				insert_date TIMESTAMP DEFAULT now()
			);");
			$this->db->execute("CREATE INDEX IF NOT EXISTS idx_hotel_wakeup_due ON public.q_hotel_wakeup_calls (status, wake_datetime);");
			$this->db->execute("CREATE INDEX IF NOT EXISTS idx_hotel_wakeup_ext ON public.q_hotel_wakeup_calls (domain_uuid, extension_uuid);");
		} catch (\Exception $e) {
			error_log("hotelWakeupCallsAction schema check failed: " . $e->getMessage());
			return;
		}

		// wake_datetime is stored as an absolute UTC instant (see
		// HotelController::wakeupSetAction()) precisely so this comparison
		// never has to guess this box's own timezone - date()/new DateTime()
		// with no explicit zone follow PHP's ambient default, which on this
		// platform is whatever the host happens to be (confirmed
		// Asia/Shanghai on at least one live box), not the hotel's.
		$hotelNow = (new DateTime("now", new DateTimeZone("UTC")))->format("Y-m-d H:i:s");

		$dueCalls = QHotelWakeupCalls::find([
			"conditions" => "status = :status: AND wake_datetime <= :now:",
			"bind" => [
				"status" => 1,
				"now" => $hotelNow,
			],
			"bindTypes" => [Column::BIND_PARAM_INT, Column::BIND_PARAM_STR],
		]);

		// Tells the tenant's front desks the room changed (the call fired,
		// failed or was rescheduled), so they re-fetch it instead of waiting
		// for their next poll. Best-effort: never stops the cron.
		$notifyRoomChanged = function ($domainName, $extension) {
			try {
				$client = new Client(Client::engine(Client::CLIENT_4X, "ws://127.0.0.1:3000", [
					"persistent" => false,
					"timeout" => 2,
				]));
				$client->initialize();
				$client->emit("hotelRooms", [
					"subdomain" => (string) $domainName,
					"extension" => (string) $extension,
				]);
				$client->close();
			} catch (\Throwable $e) {
				error_log("hotelWakeupCallsAction: hotelRooms notify failed: " . $e->getMessage());
			}
		};

		foreach ($dueCalls as $wakeupCall) {
			$vDomain = VDomains::findFirst([
				"conditions" => "domain_uuid = :domain_uuid:",
				"bind" => ["domain_uuid" => $wakeupCall->domain_uuid],
				"bindTypes" => [Column::BIND_PARAM_STR],
			]);
			if (!$vDomain) {
				$wakeupCall->status = 3;
				$wakeupCall->update();
				continue;
			}

			$ivrExtension = $this->redis->get("landing:" . $vDomain->domain_name . "-wakeup-ivr-extension");
			if (empty($ivrExtension)) {
				error_log("hotelWakeupCallsAction: no wake-up IVR extension configured for domain " . $vDomain->domain_name);
				$wakeupCall->status = 3;
				$wakeupCall->update();
				$notifyRoomChanged($vDomain->domain_name, $wakeupCall->extension);
				continue;
			}

			// Generated in PHP rather than with `uuidgen`: the container image
			// doesn't ship that binary, and an empty uuid let originate pick
			// its own, so the uuid_transfer below targeted "" and failed - the
			// answered call sat in park() and was retried as a failure.
			$uuidBytes = random_bytes(16);
			$uuidBytes[6] = chr((ord($uuidBytes[6]) & 0x0f) | 0x40);
			$uuidBytes[8] = chr((ord($uuidBytes[8]) & 0x3f) | 0x80);
			$uuid = vsprintf('%s%s-%s-%s-%s-%s%s%s', str_split(bin2hex($uuidBytes), 4));
			$result = "";
			$socket = null;
			try {
				$socket = fsockopen('127.0.0.1', 8021, $errno, $errstr, 3);
				if (!$socket) {
					throw new \Exception("ESL connect failed: $errstr");
				}
				$buffer = '';
				while (!feof($socket)) {
					$line = fgets($socket, 4096);
					if ($line === "\n") break;
					$buffer .= $line;
				}
				fwrite($socket, "auth ClueCon\n\n");
				$authResponse = '';
				while (!feof($socket)) {
					$line = fgets($socket, 4096);
					if ($line === "\n") break;
					$authResponse .= $line;
				}
				if (strpos($authResponse, '+OK accepted') === false) {
					throw new \Exception("ESL auth failed: {$authResponse}");
				}

				// Unlike "auth" (whose +OK lives in a Reply-Text header, so a
				// header-only read works for it), an "api" command's result
				// is the *body* that follows the blank line, sized by
				// Content-Length - reading only up to that blank line (as
				// this used to) always captured just the headers, so the
				// result never contained "+OK"/"-ERR" and every attempt
				// looked like a failure even when it actually succeeded.
				$readApiResponse = function () use ($socket) {
					$headers = '';
					while (!feof($socket)) {
						$line = fgets($socket, 4096);
						if ($line === false || $line === "\n" || $line === "\r\n") break;
						$headers .= $line;
					}
					$contentLength = 0;
					if (preg_match('/Content-Length:\s*(\d+)/i', $headers, $m)) {
						$contentLength = (int) $m[1];
					}
					$body = $contentLength > 0 ? fread($socket, $contentLength) : '';
					return trim($body);
				};

				// Ring the room extension and just park it once answered -
				// deliberately NOT chaining "&transfer(...)" onto originate:
				// the api command line tokenizes on whitespace before this
				// ever reaches FreeSWITCH, so a space-separated
				// "&transfer(6003 XML domain)" truncates down to just
				// "transfer(6003)", losing the dialplan/context args and
				// falling back to context "default" (where the IVR doesn't
				// exist); switching those to commas avoided the truncation
				// but then answering disconnected the call instead of
				// reaching the IVR. uuid_transfer as its own separate api
				// command - the pattern IndexController.php already uses
				// elsewhere for transferring a live call - sidesteps all of
				// that: it takes plain space-separated args like any other
				// standalone api command, no inline-app tokenizing involved.
				$cmd = "originate " .
					"{origination_uuid={$uuid}," .
					"ignore_early_media=true}" .
					"user/{$wakeupCall->extension}@{$vDomain->domain_name} &park()";
				fwrite($socket, "api {$cmd}\n\n");
				$result = $readApiResponse();

				if (strpos($result, '+OK') === 0) {
					// Answered and parked - now move that same leg (we
					// already know its uuid, since we set it ourselves as
					// origination_uuid above) into the configured wake-up
					// IVR.
					fwrite($socket, "api uuid_transfer {$uuid} {$ivrExtension} XML {$vDomain->domain_name}\n\n");
					$result = $readApiResponse();
				}
				fclose($socket);
			} catch (\Exception $e) {
				if (is_resource($socket)) {
					fclose($socket);
				}
				$result = "-ERR " . $e->getMessage();
			}

			if (strpos($result, '+OK') === 0) {
				$wakeupCall->status = 2;
				$wakeupCall->update();
			} else {
				// Retry a few times (~2 minutes apart) before giving up.
				$wakeupCall->attempts = intval($wakeupCall->attempts) + 1;
				if ($wakeupCall->attempts >= 3) {
					$wakeupCall->status = 3;
				} else {
					$retryAt = new DateTime("now", new DateTimeZone("UTC"));
					$retryAt->modify("+2 minutes");
					$wakeupCall->wake_datetime = $retryAt->format("Y-m-d H:i:s");
				}
				$wakeupCall->update();
				error_log("hotelWakeupCallsAction: originate failed for extension " . $wakeupCall->extension . " (" . $result . "), attempt " . $wakeupCall->attempts);
			}
			$notifyRoomChanged($vDomain->domain_name, $wakeupCall->extension);
		}
	}
