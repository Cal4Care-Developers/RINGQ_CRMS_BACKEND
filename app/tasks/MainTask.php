			if (isset($target['mode'])) {
				$currentMode = fileperms($path) & 0777;
				if ($currentMode !== $target['mode']) {
					$runCommand(sprintf(
						'sudo chmod -R %o %s',
						$target['mode'],
						escapeshellarg($path)
					));
				} else {
					echo "Permissions already correct for $path\n";
				}
			}

			// Executable check
			if (!empty($target['executable'])) {
				if (!is_executable($path)) {
					$runCommand(sprintf(
						'sudo chmod +x %s',
						escapeshellarg($path)
					));
