    public function processScheduledReportsAction() {
		$lockKey = "lock:scheduled_reports_processing";
		if (!$this->redis->exists($lockKey)) {
			$this->redis->setex($lockKey, 300, 1); // 5 min lock
			try {
				require_once "/var/www/ringq/app/library/ReportGenerator.php";

				$key = "scheduled_reports";
				$schedules = $this->redis->hGetAll($key);
				$timezone = date_default_timezone_get(); // System TZ, usually UTC

				echo "Checking " . count($schedules) . " scheduled reports...\n";

				foreach ($schedules as $uuid => $configJson) {
					$config = json_decode($configJson, true);
						if (!$config) {
							echo "Invalid config for UUID $uuid\n";
							continue;
						}

						$scheduleEnabled = array_key_exists('enabled', $config) ? filter_var($config['enabled'], FILTER_VALIDATE_BOOLEAN, FILTER_NULL_ON_FAILURE) : true;
						if ($scheduleEnabled === false) {
							echo "Skipping disabled scheduled report: $uuid\n";
							continue;
						}

						// `??` does not fire on an empty string, and a blank timezone is exactly what the
						// client stores for "Server Time" -- so this used to hand DateTimeZone "", throw,
						// and be swallowed by the catch below, skipping the schedule on every tick.
						$reportTimezone = $this->resolveScheduleReportTimezone(
							$config['timezone'] ?? '',
							$config['domain_uuid'] ?? null
						);
					$frequency = $config['frequency'];
					$scheduledTime = $config['time']; // HH:mm
					$lastRun = $config['last_run'] ?? 0;

					try {
						$now = new \DateTime("now", new \DateTimeZone($reportTimezone));
						$todayTime = $now->format("H:i");

						$shouldRun = false;
						$periodStart = 0;
						$periodEnd = 0;

						echo "Checking Schedule $uuid: Freq=$frequency, Time=$scheduledTime, LastRun=" . date("Y-m-d H:i", $lastRun) . ", Now=" . $now->format("Y-m-d H:i") . "\n";

						if ($frequency == "Daily") {
							$lastRunDate = (new \DateTime())->setTimestamp((int)$lastRun)->setTimezone(new \DateTimeZone($reportTimezone))->format("Y-m-d");
							$todayDate = $now->format("Y-m-d");

							// Run if not run today, and current time >= scheduled time
							if ($lastRunDate != $todayDate && $todayTime >= $scheduledTime) {
								$shouldRun = true;
								// The previous full day: a 09:00 run used to cover only 00:00-09:00 of the
								// same day. Weekly and Monthly already report the previous full period.
								$start = new \DateTime("yesterday 00:00:00", new \DateTimeZone($reportTimezone));
								$end = new \DateTime("yesterday 23:59:59", new \DateTimeZone($reportTimezone));
								$periodStart = $start->getTimestamp();
								$periodEnd = $end->getTimestamp();
							} else {
								echo "Skipping Daily: Already run today ($lastRunDate == $todayDate) or too early ($todayTime < $scheduledTime)\n";
							}
						} elseif ($frequency == "Weekly") {
							// Dynamic Day of Week
							$targetDayOfWeek = $config['day_of_week'] ?? 'Monday';
							$mapDays = [
								'Monday' => 1, 'Tuesday' => 2, 'Wednesday' => 3, 'Thursday' => 4,
								'Friday' => 5, 'Saturday' => 6, 'Sunday' => 7
							];
							$targetN = $mapDays[$targetDayOfWeek] ?? 1;

							$lastRunWeek = (new \DateTime())->setTimestamp((int)$lastRun)->setTimezone(new \DateTimeZone($reportTimezone))->format("W");
							$currentWeek = $now->format("W");

							if ($now->format("N") == $targetN && $lastRunWeek != $currentWeek && $todayTime >= $scheduledTime) {
								$shouldRun = true;
								$start = new \DateTime("monday last week midnight", new \DateTimeZone($reportTimezone));
								$end = new \DateTime("sunday last week 23:59:59", new \DateTimeZone($reportTimezone));
								$periodStart = $start->getTimestamp();
								$periodEnd = $end->getTimestamp();
							} else {
								echo "Skipping Weekly: Not $targetDayOfWeek (".$now->format("N")." vs $targetN) or already run this week ($lastRunWeek == $currentWeek) or too early.\n";
							}
						} elseif ($frequency == "Monthly") {
							// Dynamic Day of Month
							$targetDayOfMonth = $config['day_of_month'] ?? '1';

							$lastRunMonth = (new \DateTime())->setTimestamp((int)$lastRun)->setTimezone(new \DateTimeZone($reportTimezone))->format("Y-m");
							$currentMonth = $now->format("Y-m");

							// Strict check: Today's date must match target
							if ($now->format("d") == str_pad($targetDayOfMonth, 2, "0", STR_PAD_LEFT) && $lastRunMonth != $currentMonth && $todayTime >= $scheduledTime) {
								$shouldRun = true;
								// Period: Last Month
								$start = new \DateTime("first day of last month midnight", new \DateTimeZone($reportTimezone));
								$end = new \DateTime("last day of last month 23:59:59", new \DateTimeZone($reportTimezone));
								$periodStart = $start->getTimestamp();
								$periodEnd = $end->getTimestamp();
							} else {
								echo "Skipping Monthly: Not Day $targetDayOfMonth (".$now->format("d").") or already run ($lastRunMonth == $currentMonth) or too early.\n";
							}
						}

							if ($shouldRun) {
