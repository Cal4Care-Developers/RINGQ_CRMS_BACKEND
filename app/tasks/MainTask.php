		/**
		 * Email the reports one schedule run produced. Each recipient gets ONE email holding
		 * every report they are a recipient of (per-report recipient lists still decide who
		 * gets what). Returns one ['status','error'] per $generated entry, same order.
		 */
		private function sendScheduledReportEmails($generated, $config, $frequency, $periodStart, $periodEnd, $timezone, $licenseConfig) {
			$results = [];
			$byRecipient = [];
			foreach ($generated as $i => $g) {
				$results[$i] = ['status' => 'sent', 'error' => null, 'errors' => []];
