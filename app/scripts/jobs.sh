    # answers 404 -- and stayed "unavailable" until somebody pressed Update.
    # Write the same marker the update writes, under the same conditions it
    # proves from its payload: the co-located runtime and the guest client
    # (Flutter flutter_bootstrap.js, or the React build's assets/*.js) are on
    # disk. Two further conditions keep it from doing harm:
    #   * a licensed FQDN must exist, because the local install fails its
    #     `identity` gate without one -- after a heavy `dependencies` gate --
    #     and would repeat that every ten minutes until licensing finished;
    #   * an operator disable is respected (block file / operator_disabled),
    #     and so is an existing marker of any value, and a working central
    #     install (enabled under central) is left exactly as it is.
    # Guarded by ops/meet/tests/meet_topology_bootstrap_test.sh -- keep the
    # markers. Every step is non-fatal: this runs under `set -e`.
    if [ ! -s "$MEET_TOPOLOGY_FILE" ] && \
       [ -s "$MEET_LOCAL_RECONCILER" ] && \
       [ -s "$(dirname "$MEET_LOCAL_RECONCILER")/local-stack/manifest.json" ] && \
       [ -s "$MEET_WEB_CLIENT_DIR/index.html" ] && \
       { [ -s "$MEET_WEB_CLIENT_DIR/flutter_bootstrap.js" ] || \
         [ -n "$(find "$MEET_WEB_CLIENT_DIR/assets" -type f -name '*.js' -size +0 -print -quit 2>/dev/null)" ]; } && \
       [ ! -e "$MEET_STATE_DIR/automatic-activation-blocked" ] && \
       [ "$(jq -r 'if .failureCode == "operator_disabled" then "blocked" elif .enabled == true and (.topology // "central") == "central" then "central" else "" end' "$MEET_STATE_DIR/state.json" 2>/dev/null || true)" = "" ] && \
       [ -n "$(redis-cli --raw GET ringq_config 2>/dev/null | jq -r 'if ((.data.licenseKey // "") != "") and ((.data.fqdn // "") != "") then .data.fqdn else empty end' 2>/dev/null || true)" ]; then
        MEET_TOPOLOGY_DIR="$(dirname "$MEET_TOPOLOGY_FILE")"
        # Same directory treatment as the update worker: www-data (FreeSWITCH)
        # must still be able to traverse it to read config.conf.
        if mkdir -p "$MEET_TOPOLOGY_DIR" 2>/dev/null; then
            if chgrp www-data "$MEET_TOPOLOGY_DIR" 2>/dev/null; then
                chmod 0750 "$MEET_TOPOLOGY_DIR" 2>/dev/null || true
            else
                chmod 0755 "$MEET_TOPOLOGY_DIR" 2>/dev/null || true
            fi
            { printf '%s\n' local > "$MEET_TOPOLOGY_FILE.new" && \
              chmod 0644 "$MEET_TOPOLOGY_FILE.new" && \
              mv -f "$MEET_TOPOLOGY_FILE.new" "$MEET_TOPOLOGY_FILE"; } 2>/dev/null || \
                rm -f "$MEET_TOPOLOGY_FILE.new" 2>/dev/null || true
        fi
        unset MEET_TOPOLOGY_DIR
    fi
    # <<< END meet-topology-bootstrap <<<
    MEET_TOPOLOGY="central"
    if [ -s "$MEET_TOPOLOGY_FILE" ]; then
        MEET_TOPOLOGY="$(tr -d '[:space:]' < "$MEET_TOPOLOGY_FILE")"
    fi
    run_meet_reconciler() {
        local action="$1"
        local topology
        local docker_container docker_etc_volume meet_node meet_npm install_node
        if [ "$MEET_TOPOLOGY" = "local" ]; then
            topology="local"
        else
            topology="central"
        fi

        meet_runtime_contract_value() {
            local variable_name="$1" fallback="$2" value="${!1:-}"
            # Debian cron intentionally starts jobs with a small environment
            # and does not inherit Docker Compose variables. PID 1 retains the
            # container's configured environment, so root cron jobs can recover
            # these explicitly allow-listed, non-secret deployment values.
            if [ -z "$value" ] && [ -r /proc/1/environ ]; then
                value="$(tr '\0' '\n' < /proc/1/environ | sed -n "s/^${variable_name}=//p" | tail -n 1)"
            fi
            printf '%s' "${value:-$fallback}"
        }
        docker_container="$(meet_runtime_contract_value RINGQ_MEET_DOCKER_CONTAINER false)"
        docker_etc_volume="$(meet_runtime_contract_value RINGQ_MEET_DOCKER_ETC_VOLUME ringq_ringq_etc)"
        meet_node="$(meet_runtime_contract_value RINGQ_MEET_NODE /root/.nvm/versions/node/v24.12.0/bin/node)"
        meet_npm="$(meet_runtime_contract_value RINGQ_MEET_NPM /root/.nvm/versions/node/v24.12.0/bin/npm)"
        install_node="$(meet_runtime_contract_value RINGQ_MEET_INSTALL_NODE true)"

        # Docker Compose supplies the runtime contract that lets the local
        # reconciler control the host daemon safely. Plain `sudo VAR=value`
        # discarded every other RINGQ_MEET_* value, so Docker PBXs staged the
        # bare-metal LiveKit bind mount and entered a restart loop. Pass the
        # non-secret deployment contract explicitly across the privilege
        # boundary. jobs.sh normally runs as root, in which case no sudo
        # environment filtering is needed at all.
        local -a meet_environment=(
            "RINGQ_MEET_DOCKER_CONTAINER=$docker_container"
            "RINGQ_MEET_DOCKER_ETC_VOLUME=$docker_etc_volume"
            "RINGQ_MEET_NODE=$meet_node"
            "RINGQ_MEET_NPM=$meet_npm"
            "RINGQ_MEET_INSTALL_NODE=$install_node"
        )
        if [ "${EUID:-$(id -u)}" -eq 0 ]; then
            env "${meet_environment[@]}" "$MEET_RECONCILER" "$action" \
                --topology "$topology" --best-effort || true
        else
            sudo env "${meet_environment[@]}" "$MEET_RECONCILER" "$action" \
                --topology "$topology" --best-effort || true
        fi
        unset -f meet_runtime_contract_value
    }
    if [ "$(redis-cli exists restart_jobs 2>/dev/null || echo 0)" -eq 1 ]; then
        run_meet_reconciler update
    elif [ ! -s /var/lib/ringq-meet/state.json ]; then
        if [ "$MEET_TOPOLOGY" = "local" ]; then
            # A co-located server owns its own Gateway and SFU, so a first
            # installation needs no external enrollment: `update` decides for
            # itself whether the licence and FQDN permit activation and falls
            # back to install-disabled when they do not.
            #
            # This must not wait for `restart_jobs`. That key is consumed by the
            # first jobs.sh run after an update, which on a Docker PBX can be the
            # run that happens *before* the host applies the deployment contract
            # — leaving a payload that is present, a contract that arrived a
            # moment later, and nothing left to trigger the installation until
            # the customer pressed Update a second time.
            run_meet_reconciler update
        else
            # Central topology stays disabled until the trusted licensing flow
            # invokes the explicit activate action.
            run_meet_reconciler install-disabled
        fi
    elif [ "$MEET_TOPOLOGY" = "local" ] && \
         { [ "$(jq -r '.enabled // false' /var/lib/ringq-meet/state.json 2>/dev/null)" != "true" ] || \
           [ "$(jq -r '.failureCode // ""' /var/lib/ringq-meet/state.json 2>/dev/null)" != "" ]; } && \
         [ "$(find /var/lib/ringq-meet/state.json -mmin +10 -print 2>/dev/null)" != "" ]; then
        # A co-located installation retries every ten minutes while it is not
        # yet enabled, and also while the last run recorded a failure: a
        # candidate that failed and rolled back leaves Meet enabled on the old
        # release, so "enabled" alone would call that settled and never retry. A first install
        # pulls a 4 GB Egress image on a two-core server, so the health gate can
        # legitimately lose the race once; a full day of downtime afterwards is
        # not an acceptable price for that.
        run_meet_reconciler update
    elif [ "$MEET_TOPOLOGY" = "local" ] && \
         [ "$(jq -r '.topology // "central"' /var/lib/ringq-meet/state.json 2>/dev/null)" != "local" ]; then
        # The marker is the authority on topology, and state recorded under a
        # different one is stale. This happens on a first update: cron can start
        # jobs.sh after the payload has landed but before the update writes the
        # marker, and that run records `central` and installs disabled. Without
        # this the server then looks settled — state exists and is fresh — and
        # Meet waits a full day, or a second Update click, for a topology it was
        # already told about.
        run_meet_reconciler update
    elif { [ -s /etc/ringq/pki/tenant-control-plane.crt ] && ! openssl x509 -checkend 604800 -noout -in /etc/ringq/pki/tenant-control-plane.crt >/dev/null 2>&1; } || \
         { [ "$(find /var/lib/ringq-meet/state.json -mmin +1440 -print 2>/dev/null)" != "" ]; }; then
        # Refresh entitlement and renew certificates at most daily. A healthy,
        # unchanged release stays enabled while these checks run.
        if [ "$MEET_TOPOLOGY" = "local" ]; then
            run_meet_reconciler update
        elif [ "$(jq -r '.enabled // false' /var/lib/ringq-meet/state.json 2>/dev/null)" = "true" ]; then
            run_meet_reconciler activate
        else
            run_meet_reconciler install-disabled
        fi
    fi
    unset -f run_meet_reconciler
    unset MEET_TOPOLOGY
fi

# >>> BEGIN pm2-node-runtimes >>>
# PM2 apps whose interpreter is an nvm Node (/root/.nvm/versions/node/vX.Y.Z/bin/node) cannot start
# until that version is installed. Install any missing one here, before the PM2 check below.
# meeting and meeting-summary are left to ringq-meet-reconcile, which installs their Node itself.
# A failed install is retried at most once an hour.
PM2_NVM_DIR="${RINGQ_PM2_NVM_DIR:-/root/.nvm}"
PM2_NODE_STATE_DIR="${RINGQ_PM2_NODE_STATE_DIR:-/var/lib/ringq}"
PM2_NODE_LOG="${RINGQ_PM2_NODE_LOG:-/var/log/ringq/node-install.log}"
if [ -s "$ECOSYSTEM_CONFIG" ]; then
    PM2_NODE_VERSIONS=$(awk '
        /^[[:space:]]*\/\// { next }
        /name:/ { name = $0; sub(/.*name:[[:space:]]*./, "", name); sub(/[^A-Za-z0-9_.-].*/, "", name) }
        /interpreter:/ && match($0, /\/versions\/node\/v[0-9]+\.[0-9]+\.[0-9]+\//) {
            if (name != "meeting" && name != "meeting-summary") print substr($0, RSTART + 16, RLENGTH - 17)
        }' "$ECOSYSTEM_CONFIG" 2>/dev/null | sort -u) || true
    for PM2_NODE_V in $PM2_NODE_VERSIONS; do
        [ -x "$PM2_NVM_DIR/versions/node/v$PM2_NODE_V/bin/node" ] && continue
        PM2_NODE_STAMP="$PM2_NODE_STATE_DIR/node-install-v$PM2_NODE_V.failed"
        if [ -f "$PM2_NODE_STAMP" ] && \
           [ $(( $(date +%s) - $(stat -c %Y "$PM2_NODE_STAMP" 2>/dev/null || echo 0) )) -lt 3600 ]; then
            continue
        fi
        echo "Installing Node v$PM2_NODE_V for PM2 apps..."
        mkdir -p "$PM2_NODE_STATE_DIR" "$(dirname "$PM2_NODE_LOG")" 2>/dev/null || true
        if timeout --kill-after=10s 600s bash -c '
            set +eu
            export NVM_DIR="$1"
            if [ ! -s "$NVM_DIR/nvm.sh" ]; then
                command -v git >/dev/null 2>&1 || { echo "nvm not found at $NVM_DIR and git is not installed"; exit 1; }
                nvm_tmp=$(mktemp -d) || exit 1
                if git clone --quiet --depth 1 --branch v0.40.3 https://github.com/nvm-sh/nvm.git "$nvm_tmp/nvm"; then
                    mkdir -p "$NVM_DIR" && cp -a "$nvm_tmp/nvm/." "$NVM_DIR/"
                fi
                rm -rf "$nvm_tmp"
                [ -s "$NVM_DIR/nvm.sh" ] || { echo "nvm could not be installed at $NVM_DIR"; exit 1; }
                if [ "$NVM_DIR" = /root/.nvm ] && [ -f /root/.bashrc ] && ! grep -q "NVM_DIR=\"/root/.nvm\"" /root/.bashrc; then
                    echo "export NVM_DIR=\"/root/.nvm\"" >> /root/.bashrc
                    echo "[ -s \"\$NVM_DIR/nvm.sh\" ] && . \"\$NVM_DIR/nvm.sh\"" >> /root/.bashrc
                fi
            fi
            . "$NVM_DIR/nvm.sh"
            had_default=$(nvm alias default 2>/dev/null)
            nvm install "$2" || exit 1
            [ -n "$had_default" ] || nvm unalias default >/dev/null 2>&1
            [ -x "$NVM_DIR/versions/node/v$2/bin/node" ]
        ' _ "$PM2_NVM_DIR" "$PM2_NODE_V" </dev/null >>"$PM2_NODE_LOG" 2>&1; then
            rm -f "$PM2_NODE_STAMP"
            echo "Node v$PM2_NODE_V installed."
        else
            touch "$PM2_NODE_STAMP" 2>/dev/null || true
            echo "Warning: Node v$PM2_NODE_V could not be installed (see $PM2_NODE_LOG); retrying in an hour."
        fi
    done
    unset PM2_NODE_VERSIONS PM2_NODE_V PM2_NODE_STAMP
fi
