def server_starts(src):
    return [m for m in re.finditer(r'^[ \t]*server\s*\{[^\n]*\n', src, flags=re.M)]


def blocks(text):
    """(open_line_end, close_index, kind) for every server/location block."""
    found = []
    for m in re.finditer(r'^[ \t]*(server|location)\b[^{;\n]*\{[^\n]*\n', text, flags=re.M):
        depth = 0
        i = m.start() + m.group(0).index('{')
        while i < len(text):
            if text[i] == '{':
                depth += 1
            elif text[i] == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        found.append((m.end(), i, m.group(1)))
    return found


def direct_body(text, start, end):
    """The block's own lines, with nested blocks removed."""
    out, depth, i = [], 0, start
    while i < end:
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
        elif depth == 0:
            out.append(c)
        i += 1
    return ''.join(out)


def add_headers(text, headers):
    marker = headers[0]
    inserts = []
    for start, end, kind in blocks(text):
        body = direct_body(text, start, end)
        if marker in body:
            continue
        if kind == 'server' or re.search(r'^\s*add_header\s', body, flags=re.M):
            line_start = text.rfind('\n', 0, start - 1) + 1
            opener = text[line_start:start]
            indent = re.match(r'[ \t]*', opener).group(0) + '    '
            anchor = start
            gate = text[start:].split('\n', 1)[0]
            if kind == 'server' and '$ringq_block_tools' in gate:
                anchor = start + len(gate) + 1
            inserts.append((anchor, ''.join(indent + h + '\n' for h in headers)))
    for at, chunk in sorted(inserts, reverse=True):
        text = text[:at] + chunk + text[at:]
    return text


def block_tools(text):
    text = OLD_BLOCKED.sub('', text)
    out = []
    pos = 0
    for m in server_starts(text):
        depth = 0
        i = m.start() + m.group(0).index('{')
        end = len(text)
        while i < len(text):
            if text[i] == '{':
                depth += 1
            elif text[i] == '}':
                depth -= 1
                if depth == 0:
                    end = i + 1
                    break
            i += 1
        if '$ringq_block_tools' in text[m.start():end]:
            continue
        out.append(text[pos:m.end()])
        out.append(BLOCKED)
        pos = m.end()
    out.append(text[pos:])
    return ''.join(out)


def upsert(text, block, after=None):
    begin = block.split('\n', 1)[0] + '\n'
    end = [l for l in block.split('\n') if l.startswith('# <<< ')][0] + '\n'
    if begin in text:
        a = text.index(begin)
        b = text.index(end, a) + len(end)
        return text[:a] + block + text[b:]
    if after and after in text:
        at = text.index(after) + len(after)
        return text[:at] + block + text[at:]
    return block + text


def maps(text):
    text = upsert(text, CORS_MAP)
    text = upsert(text, TOOLS_MAP, '# <<< ringq-security: cors allow-list <<<\n')
    text = upsert(text, HEADERS_MAP, '# <<< ringq-security: admin tools <<<\n')
    return re.sub(r'(add_header\s+Access-Control-Allow-Origin\s+)\$http_origin\b',
                  r'\1$ringq_cors_origin', text)


