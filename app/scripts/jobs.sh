def is_static_header(line):
    # Regex location matching an extension group, e.g. `location ~* \.(css|js)$`.
    # Never matches `location ~ \.php`, `location /`, or `location = /favicon.ico`.
    return '~*' in line and '\\.(' in line


def remove_static_locations(text):
    lines = text.splitlines(keepends=True)
    out = []
    i = 0
    removed = 0
    while i < len(lines):
        line = lines[i]
        if re.match(r'^[ \t]*location\b', line) and '{' in line and is_static_header(line):
            depth = line.count('{') - line.count('}')
            i += 1
            while i < len(lines) and depth > 0:
                depth += lines[i].count('{') - lines[i].count('}')
                i += 1
            while i < len(lines) and lines[i].strip() == '':
                i += 1
            removed += 1
            continue
        out.append(line)
        i += 1
    return ''.join(out), removed


