          OR (c.table_name = 'v_contact_settings' AND c.column_name = 'contact_setting_enabled')
          OR (c.table_name = 'v_contact_addresses' AND c.column_name = 'address_primary')
          OR (c.table_name = 'v_contact_emails' AND c.column_name = 'email_primary')
          OR (c.table_name = 'v_contact_phones' AND c.column_name = 'phone_primary')
          OR (c.table_name = 'v_contact_urls' AND c.column_name = 'url_primary')
        ))
        OR (c.table_name = 'v_gateways' AND c.column_name = 'privacy_header' AND c.data_type = 'integer')
      )
  LOOP
    -- save and drop views that depend on this table (they block type changes)
    FOR vw IN
      SELECT DISTINCT dv.oid, dv.relname, pg_get_userbyid(dv.relowner) AS owner
      FROM pg_depend d
      JOIN pg_rewrite rw ON rw.oid = d.objid
