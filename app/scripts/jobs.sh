# >>> BEGIN ringq-swap >>>
# Small servers (under 3.5 GiB RAM) get a 2 GiB /swapfile on the host when no swap is active, so a memory spike
# swaps instead of the kernel killing FreeSWITCH, PM2 or the Meet transcriber (seen on a 2 GB Docker PBX).
# On Docker the container's root is overlay, where swapon fails, so the swap is made on the host through a
# one-off privileged helper from the same RingQ image. /etc/ringq-swap.disabled on the host turns this off.
# A failed attempt is retried at most once an hour.
RINGQ_SWAP_HOST_SCRIPT='
PATH="${RINGQ_SWAP_PATH:-/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin}"; export PATH
SWAP=${RINGQ_SWAP_FILE:-/swapfile}
FSTAB=${RINGQ_SWAP_FSTAB:-/etc/fstab}
SYSCTL=${RINGQ_SWAP_SYSCTL:-/etc/sysctl.d/99-ringq-swap.conf}
PROC_SWAPS=${RINGQ_SWAP_PROC_SWAPS:-/proc/swaps}
PROC_MEM=${RINGQ_SWAP_PROC_MEMINFO:-/proc/meminfo}
OFF=${RINGQ_SWAP_DISABLED_FILE:-/etc/ringq-swap.disabled}
[ -f "$OFF" ] && { echo "swap: disabled by $OFF"; exit 0; }
[ "$(awk "NR>1" "$PROC_SWAPS" | wc -l)" -gt 0 ] && { echo "swap: already active"; exit 0; }
mem_kb=$(awk "/^MemTotal:/{print \$2}" "$PROC_MEM")
[ "${mem_kb:-0}" -ge 3670016 ] && { echo "swap: not needed (${mem_kb} kB RAM)"; exit 0; }
dir=$(dirname "$SWAP")
fstype=$(df -PT "$dir" 2>/dev/null | awk "NR==2{print \$2}")
case "$fstype" in ext4|xfs) ;; *) echo "swap: unsupported filesystem ${fstype:-unknown} for $SWAP"; exit 1 ;; esac
if [ -f "$SWAP" ] && swapon "$SWAP" 2>/dev/null; then
    echo "swap: re-enabled existing $SWAP"
else
    avail_kb=$(df -Pk "$dir" | awk "NR==2{print \$4}")
    [ -f "$SWAP" ] && avail_kb=$(( avail_kb + $(du -k "$SWAP" | cut -f1) ))
    [ "${avail_kb:-0}" -ge 3145728 ] || { echo "swap: not enough free disk (${avail_kb} kB, need 3 GiB)"; exit 1; }
    rm -f "$SWAP"
    if ! { fallocate -l 2G "$SWAP" 2>/dev/null && chmod 600 "$SWAP" && mkswap "$SWAP" >/dev/null 2>&1 && swapon "$SWAP" 2>/dev/null; }; then
        rm -f "$SWAP"
        dd if=/dev/zero of="$SWAP" bs=1M count=2048 status=none && chmod 600 "$SWAP" && mkswap "$SWAP" >/dev/null 2>&1 && swapon "$SWAP" \
            || { rm -f "$SWAP"; echo "swap: could not create $SWAP"; exit 1; }
    fi
    echo "swap: created 2 GiB $SWAP"
fi
grep -qE "^[[:space:]]*$SWAP[[:space:]]" "$FSTAB" 2>/dev/null || echo "$SWAP none swap sw 0 0" >> "$FSTAB"
sysctl -w vm.swappiness=10 >/dev/null 2>&1 || true
mkdir -p "$(dirname "$SYSCTL")" && printf "vm.swappiness=10\n" > "$SYSCTL"
exit 0
'
RINGQ_SWAP_STAMP="${RINGQ_SWAP_STATE_DIR:-/var/lib/ringq}/swap.failed"
if [ "$(awk 'NR>1' "${RINGQ_SWAP_PROC_SWAPS:-/proc/swaps}" 2>/dev/null | wc -l)" -eq 0 ] && \
   [ "$(awk '/^MemTotal:/{print $2}' "${RINGQ_SWAP_PROC_MEMINFO:-/proc/meminfo}" 2>/dev/null || echo 0)" -lt 3670016 ] && \
   { [ ! -f "$RINGQ_SWAP_STAMP" ] || \
     [ $(( $(date +%s) - $(stat -c %Y "$RINGQ_SWAP_STAMP" 2>/dev/null || echo 0) )) -ge 3600 ]; }; then
    if [ "$(findmnt -no FSTYPE / 2>/dev/null)" = "overlay" ] || [ -f /.dockerenv ]; then
        RINGQ_SWAP_IMAGE=$(timeout 20s docker inspect -f '{{.Image}}' "${RINGQ_SWAP_CONTAINER:-ringq}" 2>/dev/null) || RINGQ_SWAP_IMAGE=""
        if [ -n "$RINGQ_SWAP_IMAGE" ]; then
            RINGQ_SWAP_OUT=$(printf '%s' "$RINGQ_SWAP_HOST_SCRIPT" | timeout --kill-after=10s 300s docker run --rm -i \
                --privileged --pid=host --network=none --entrypoint nsenter "$RINGQ_SWAP_IMAGE" \
                -t 1 -m -u -i -n -- sh -s 2>&1) && RINGQ_SWAP_RC=0 || RINGQ_SWAP_RC=1
        else
            RINGQ_SWAP_OUT="swap: cannot find the RingQ container image to reach the host"; RINGQ_SWAP_RC=1
        fi
    else
        RINGQ_SWAP_OUT=$(printf '%s' "$RINGQ_SWAP_HOST_SCRIPT" | timeout --kill-after=10s 300s sh -s 2>&1) && RINGQ_SWAP_RC=0 || RINGQ_SWAP_RC=1
    fi
    echo "$RINGQ_SWAP_OUT" | tail -1
    if [ "$RINGQ_SWAP_RC" -eq 0 ]; then
        rm -f "$RINGQ_SWAP_STAMP"
    else
        mkdir -p "$(dirname "$RINGQ_SWAP_STAMP")" 2>/dev/null || true
        touch "$RINGQ_SWAP_STAMP" 2>/dev/null || true
    fi
    unset RINGQ_SWAP_IMAGE RINGQ_SWAP_OUT RINGQ_SWAP_RC
fi
unset RINGQ_SWAP_HOST_SCRIPT RINGQ_SWAP_STAMP
# <<< END ringq-swap <<<

# `pm2 jlist` can hang for good: when it can't reach the running PM2 daemon it starts a second
# one and waits on it forever (seen at midnight on 165, 178 and Skyrock, with a new stuck run and
# daemon every night). Give it 20 s. Without an answer, skip the PM2 check for this run: an empty
# list would make every app look offline and restart all of them.
# Through a file, not $(...): a daemon it leaves behind must not hold our pipe open.
PM2_JLIST_FILE=$(mktemp)
timeout --kill-after=5s 20s pm2 jlist >"$PM2_JLIST_FILE" 2>/dev/null </dev/null || true
PM2_JLIST=$(cat "$PM2_JLIST_FILE")
rm -f "$PM2_JLIST_FILE"
if ! printf '%s' "$PM2_JLIST" | jq -e 'type == "array"' >/dev/null 2>&1; then
    echo "Warning: pm2 jlist did not answer within 20 seconds; skipping the PM2 check this run."
    PM2_JLIST=""
fi

if [ -f "$ECOSYSTEM_CONFIG" ] && [ -n "$PM2_JLIST" ]; then
    EXPECTED_APPS=$(grep -v '^[[:space:]]*//' "$ECOSYSTEM_CONFIG" | grep -o "name: *['\"][^'\"]*['\"]" | sed -E "s/name: *['\"]([^'\"]*)['\"]/\1/") || true
    if [ ! -f /opt/ringq-meet-control-plane/current/server.js ]; then
        # Meet is optional and fail-closed. A missing candidate must never stop
        # chat, CRM, transcript, or the rest of the RingQ PM2 reconciliation.
        EXPECTED_APPS=$(printf '%s\n' "$EXPECTED_APPS" | grep -vx meeting || true)
    fi
    
    ONLINE_APPS_LIST=$(printf '%s' "$PM2_JLIST" | jq -r '.[] | select(.pm2_env.status == "online") | .name')
    ALL_EXISTING_APPS=$(printf '%s' "$PM2_JLIST" | jq -r '.[] | .name')
    
    NOT_ONLINE_APPS=()
    if [ -n "$EXPECTED_APPS" ]; then
        for APP in $EXPECTED_APPS; do
            if ! echo "$ONLINE_APPS_LIST" | grep -q "^$APP$"; then
                echo "Error: App '$APP' is NOT online."
                NOT_ONLINE_APPS+=("$APP")
            fi
        done
    fi

    CLEANUP_NEEDED=false
    # An empty EXPECTED_APPS must never reach this loop. Every running process
    # fails the membership test against an empty list, so the loop would delete
    # the entire PBX - server, signal, status, attended, queue, sso, meeting.
    # That list is legitimately empty on a Docker PBX, where every `name:` in
    # ecosystem.config.js is commented out by design and ringq_installer.sh
    # starts the seven apps individually. Until the `|| true` was added above,
    # `set -e` aborting on the failed grep was the only thing preventing this;
    # the offline loop above has always carried the same guard.
    if [ -n "$EXPECTED_APPS" ]; then
        for RUNNING_APP in $ALL_EXISTING_APPS; do
            if [ "$RUNNING_APP" = "pm2-logrotate" ] || [ "$RUNNING_APP" = "pm2-server-monit" ]; then
                 continue
            fi

            if ! echo "$EXPECTED_APPS" | grep -q "^$RUNNING_APP$"; then
                echo "Warning: App '$RUNNING_APP' is running but not in config (or commented out). Removing..."
                timeout --kill-after=5s 60s pm2 delete "$RUNNING_APP" </dev/null || true
                CLEANUP_NEEDED=true
            fi
        done
    fi

    if [ "${#NOT_ONLINE_APPS[@]}" -gt 0 ]; then
        echo "Restarting offline apps: ${NOT_ONLINE_APPS[*]}"
        for APP in "${NOT_ONLINE_APPS[@]}"; do
            # Bounded like `pm2 jlist` above: at midnight a restart that can't reach the daemon
            # waits on it forever and holds the run lock with it.
            if ! timeout --kill-after=5s 60s pm2 restart "$APP" </dev/null 2>/dev/null && \
               ! timeout --kill-after=5s 60s pm2 start "$ECOSYSTEM_CONFIG" --only "$APP" </dev/null; then
                echo "Warning: PM2 app '$APP' could not be started; continuing with remaining apps."
            fi
        done
        timeout --kill-after=5s 60s pm2 save </dev/null || true
    fi

    if [ "$CLEANUP_NEEDED" = true ]; then
        echo "Saving PM2 config after cleanup..."
        # Do not startOrReload the whole ecosystem here: optional applications
        # filtered above may intentionally have no runnable artifact.
        timeout --kill-after=5s 60s pm2 save </dev/null || true
    fi

    if [ "${#NOT_ONLINE_APPS[@]}" -eq 0 ] && [ "$CLEANUP_NEEDED" = false ]; then
        echo "PM2 Status: All expected apps are online and synced."
    fi

    # >>> BEGIN pm2-app-drift >>>
    # `pm2 restart` keeps the script and interpreter an app was first started with. When
    # ecosystem.config.js changes either (a renamed script, a new nvm Node), recreate that app
    # from the ecosystem file. meeting and meeting-summary are left to ringq-meet-reconcile.
    PM2_DRIFT_APPS=""
    while IFS=$'\t' read -r APP WANT_SCRIPT WANT_INTERP; do
        [ -n "$APP" ] && [ -n "$WANT_SCRIPT" ] || continue
        case "$APP" in meeting|meeting-summary) continue ;; esac
        echo "$EXPECTED_APPS" | grep -qx "$APP" || continue
        HAVE=$(printf '%s' "$PM2_JLIST" | jq -r --arg n "$APP" \
            '[.[] | select(.name == $n)][0] | if . == null then empty else "\(.pm2_env.pm_exec_path // "")\t\(.pm2_env.exec_interpreter // "")" end' 2>/dev/null) || continue
        [ -n "$HAVE" ] || continue
        HAVE_SCRIPT=${HAVE%%$'\t'*}; HAVE_INTERP=${HAVE#*$'\t'}
        [ -n "$HAVE_SCRIPT" ] || continue
        [ -f "$WANT_SCRIPT" ] || continue
        DRIFT=""
        [ "$(readlink -f "$HAVE_SCRIPT" 2>/dev/null || echo "$HAVE_SCRIPT")" = "$(readlink -f "$WANT_SCRIPT")" ] || DRIFT="script $HAVE_SCRIPT -> $WANT_SCRIPT"
        case "$WANT_INTERP" in
            /*) [ -x "$WANT_INTERP" ] && [ "$HAVE_INTERP" != "$WANT_INTERP" ] && DRIFT="${DRIFT:+$DRIFT, }interpreter $HAVE_INTERP -> $WANT_INTERP" ;;
        esac
        if [ -n "$DRIFT" ]; then
            echo "PM2 app '$APP' differs from ecosystem.config.js ($DRIFT); recreating it."
            timeout --kill-after=5s 60s pm2 delete "$APP" </dev/null >/dev/null 2>&1 || true
            if timeout --kill-after=5s 60s pm2 start "$ECOSYSTEM_CONFIG" --only "$APP" </dev/null >/dev/null 2>&1; then
                PM2_DRIFT_APPS="$PM2_DRIFT_APPS $APP"
            else
                echo "Warning: PM2 app '$APP' could not be started from ecosystem.config.js; trying again next run."
            fi
        fi
    done < <(awk '
        function flush() { if (name != "") printf "%s\t%s\t%s\n", name, script, interp; name = script = interp = "" }
        /^[[:space:]]*\/\// { next }
        /name:/ { flush(); name = $0; sub(/.*name:[[:space:]]*./, "", name); sub(/[^A-Za-z0-9_.-].*/, "", name) }
        /script:/ { script = $0; sub(/.*script:[[:space:]]*./, "", script); sub(/[^A-Za-z0-9_.\/-].*/, "", script) }
