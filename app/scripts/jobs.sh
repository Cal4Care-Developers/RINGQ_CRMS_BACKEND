e /tmp - - - 1h wireshark_*.pcapng
e /tmp/sip-ring - - - 1h ring_*.pcap
EOF
)
        if [ ! -f "$TMPFILES_CONF" ] || ! printf '%s\n' "$TMPFILES_DESIRED" | cmp -s - "$TMPFILES_CONF"; then
            printf '%s\n' "$TMPFILES_DESIRED" > "$TMPFILES_CONF"
            sudo systemd-tmpfiles --create "$TMPFILES_CONF" >/dev/null 2>&1 || true
        fi

        # Purge legacy /var/spool/pcapsipdump (replaced by sip-pcap-daemon).
        # Layout has date-named subdirectories (YYYYMMDD/), so cannot use
        # -maxdepth 1. Guard: dir exists AND service inactive AND dir non-empty.
        # No marker file — directory emptiness is the natural idempotency check.
        if [ -d /var/spool/pcapsipdump ] \
           && ! systemctl is-active --quiet pcapsipdump 2>/dev/null \
           && [ -n "$(ls -A /var/spool/pcapsipdump 2>/dev/null)" ]; then
            find /var/spool/pcapsipdump -type f \( -name '*.pcap' -o -name '*.pcapng' \) -delete 2>/dev/null || true
            find /var/spool/pcapsipdump -depth -type d -empty -delete 2>/dev/null || true
        fi

        if [ -f "$CDR_SERVICE_DST" ] \
           && [ -f "$CDR_TIMER_DST" ] \
           && systemctl is-active --quiet calldetailrecord.timer \
           && cmp -s "$CDR_SERVICE_SRC" "$CDR_SERVICE_DST" 2>/dev/null \
           && cmp -s "$CDR_TIMER_SRC" "$CDR_TIMER_DST" 2>/dev/null; then
            echo "calldetailrecord.timer already configured — skipping."
        else
            CDR_DIRTY=0

            if [ -f "$CDR_SERVICE_SRC" ]; then
                if [ ! -f "$CDR_SERVICE_DST" ] || ! cmp -s "$CDR_SERVICE_SRC" "$CDR_SERVICE_DST"; then
                    sudo cp "$CDR_SERVICE_SRC" "$CDR_SERVICE_DST"
                    CDR_DIRTY=1
                fi
            fi

            if [ -f "$CDR_TIMER_SRC" ]; then
                if [ ! -f "$CDR_TIMER_DST" ] || ! cmp -s "$CDR_TIMER_SRC" "$CDR_TIMER_DST"; then
                    sudo cp "$CDR_TIMER_SRC" "$CDR_TIMER_DST"
                    CDR_DIRTY=1
                fi
            fi

            if [ "$CDR_DIRTY" = "1" ]; then
                sudo systemctl daemon-reload
                sudo systemctl enable calldetailrecord.timer 2>/dev/null || true
                sudo systemctl restart calldetailrecord.timer
            elif ! systemctl is-active --quiet calldetailrecord.timer; then
                sudo systemctl daemon-reload
                sudo systemctl enable --now calldetailrecord.timer 2>/dev/null || true
            fi
        fi

        # ── NX Device tunnel firewall (th-changes pbx-setup.sh semantics) ────────
        # Delete-then-recreate: each cycle clears ALL rules matching the tunnel
        # ports (any IP) and recreates them from the current FS internal IP, so
        # rules pointing at an old FS IP never go stale. FreeSWITCH is still up
        # here (restart is the last step of this block), so `sofia status`
        # yields the live internal IP.
        FS_INTERNAL_IP=$(fs_cli -x 'sofia status' 2>/dev/null \
            | grep -oP '\d+\.\d+\.\d+\.\d+' | head -1 || echo "127.0.0.1")

        _ipt_clear_by_dport() {   # table chain dport — line-number delete, reversed
            local table="$1" chain="$2" dport="$3" tbl_flag=""
            [ "$table" = "nat" ] && tbl_flag="-t nat"
            local lines line
            # `|| true`: with no matching rules grep exits 1; jobs.sh runs with
            # pipefail set globally, so guard the assignment or a clean chain
            # would fail the pipeline (fatal anywhere errexit is re-enabled).
            lines=$(iptables $tbl_flag -L "$chain" --line-numbers -n 2>/dev/null \
                | grep "dpt:${dport}" | awk '{print $1}' | sort -rn) || true
            for line in $lines; do
                iptables $tbl_flag -D "$chain" "$line" 2>/dev/null || true
            done
        }

        # Rule 1: INPUT tcp/${TUNNEL_PORT} — delete exact if present, then add fresh.
        if iptables -C INPUT -p tcp --dport "${TUNNEL_PORT}" -j ACCEPT 2>/dev/null; then
            iptables -D INPUT -p tcp --dport "${TUNNEL_PORT}" -j ACCEPT
        fi
        iptables -A INPUT -p tcp --dport "${TUNNEL_PORT}" -j ACCEPT
        echo "  [SET] INPUT tcp/${TUNNEL_PORT}"

        # Rule 2: DNAT tcp/${TUNNEL_PORT} -> FS_IP:${FS_SIP_PORT} — clear by port
        # so stale rules pointing at an OLD FS IP are removed, then recreate.
        _ipt_clear_by_dport nat PREROUTING "${TUNNEL_PORT}"
        iptables -t nat -A PREROUTING -p tcp --dport "${TUNNEL_PORT}" \
            -j DNAT --to-destination "${FS_INTERNAL_IP}:${FS_SIP_PORT}"
        echo "  [SET] DNAT tcp/${TUNNEL_PORT} -> ${FS_INTERNAL_IP}:${FS_SIP_PORT}"

        # Rule 3: FORWARD tcp -> FS_IP:${FS_SIP_PORT} — same clear-by-port reasoning.
        _ipt_clear_by_dport filter FORWARD "${FS_SIP_PORT}"
        iptables -A FORWARD -p tcp -d "${FS_INTERNAL_IP}" --dport "${FS_SIP_PORT}" -j ACCEPT
        echo "  [SET] FORWARD tcp -> ${FS_INTERNAL_IP}:${FS_SIP_PORT}"

        # >>> BEGIN client-socket-ports >>>
        # Older installers opened these with `-i eth0`. On a host whose NIC is
        # not eth0 (ens3/enp* on KVM/OpenStack) that rule never matches, and
        # with `-P INPUT DROP` the port is closed: 9999 closed means the mobile
        # app cannot reach status.js, so `push-call` finds no registered socket
        # and Android push silently never fires. Deliberately no `-i` so the
        # rule cannot depend on an interface name again. 9886 stays closed.
        for _csp in 9999 8886; do
            if iptables -C INPUT -p tcp --dport "$_csp" -j ACCEPT 2>/dev/null; then
                echo "  [OK]  INPUT tcp/${_csp}"
            elif iptables -A INPUT -p tcp --dport "$_csp" -j ACCEPT 2>/dev/null; then
                echo "  [SET] INPUT tcp/${_csp}"
            else
                echo "  [WARN] could not open INPUT tcp/${_csp}"
            fi
        done
        unset _csp
        # <<< END client-socket-ports <<<

        mkdir -p /etc/iptables
        # Write to a temp file first: `iptables-save > file` truncates the
        # destination before the command runs, so any failure (missing binary,
        # kernel error) would leave rules.v4 empty.
        if iptables-save > "${IPT_RULES_V4}.tmp" 2>/dev/null; then
            mv "${IPT_RULES_V4}.tmp" "$IPT_RULES_V4"
            echo "  [SAVED] $IPT_RULES_V4"
        else
            rm -f "${IPT_RULES_V4}.tmp"
            echo "  [WARN] iptables-save failed — $IPT_RULES_V4 left untouched"
        fi

        # One-time security maintenance task, guarded by the local redis key
        # "maintask-security" so it only ever runs once per server. Mirrors the
        # equivalent step in fileserver_143.198.209.102/rsyncher update_customer.sh so servers
        # whose update path only sets restart_jobs (no rsync push from the
        # fileserver_143.198.209.102) still receive it. Non-fatal: this block runs under `set +e`,
        # so a failure here can never abort the rest of the restart_jobs work.
        if [ "$(redis-cli EXISTS maintask-security)" = "1" ]; then
            echo "[security] maintask-security key exists, skipping security task"
        elif [ -f /var/www/ringq/app/cli.php ]; then
            /usr/bin/php /var/www/ringq/app/cli.php main security 2>&1 | sed 's/^/[security] /'
            _sec_rc=${PIPESTATUS[0]}
            if [ "$_sec_rc" -eq 0 ]; then
                redis-cli SET maintask-security 1 >/dev/null
                echo "[security] Security task completed, maintask-security set to 1"
            else
                echo "[security] Security task exited with code $_sec_rc (non-fatal, will retry on next update)"
            fi
            unset _sec_rc
        fi

        # >>> BEGIN cm-adjustments-run >>>
        # CM ADJUSTMENT (added by CM / Mani): after every update re-apply the RingQ server-side
        # fixes the update package does not install by itself (FreeSWITCH scripts, dialplans --
        # incl. local_extension, which the central SQL resets to stock --, tables, health check,
        # nginx LAN provisioning). Non-fatal: this block runs under `set +e`.
        if declare -F cm_adjustments >/dev/null; then
            cm_adjustments
            _cm_rc=$?
            [ "$_cm_rc" -eq 0 ] || echo "[cm] CM adjustments returned $_cm_rc (non-fatal, see /var/log/ringq-cm-install.log)"
            unset _cm_rc
        fi
        # <<< END cm-adjustments-run <<<

        mkdir -p /var/pcap
        chmod 755 /var/pcap
        chown www-data:www-data /var/pcap

        mkdir -p /etc/systemd/system/php7.4-fpm.service.d
        cat > /etc/systemd/system/php7.4-fpm.service.d/network-capture.conf <<'EOF'
[Service]
PrivateDevices=false
RestrictAddressFamilies=AF_INET AF_INET6 AF_NETLINK AF_UNIX AF_PACKET
EOF
        sudo systemctl daemon-reload
        sudo systemctl restart php7.4-fpm

        sudo systemctl restart freeswitch 2>/dev/null || sudo service freeswitch restart 2>/dev/null || true
        sudo service redis-server restart
        sudo service fail2ban reload
        sudo service php7.4-fpm reload
        sudo service nginx reload
        # Loads the Update's node code. Bounded so a stuck PM2 client can't hold the run lock.
        if ! sudo timeout --signal=TERM --kill-after=15s 180s pm2 reload all </dev/null; then
            echo "Warning: pm2 reload all did not finish within 180 seconds; the stale-code check reloads the apps on the next runs."
        fi
        # PM2 has occasionally left `pm2 update` attached indefinitely after
        # all applications were already reloaded. Bound this maintenance step
        # so one stale PM2 client cannot hold the entire update job forever.
        if ! sudo timeout --signal=TERM --kill-after=15s 120s pm2 update; then
            echo "Warning: pm2 update did not complete within 120 seconds; applications were already reloaded."
        fi
        set -e

        redis-cli del restart_lock >/dev/null
    fi
fi
