# One run at a time. Cron starts jobs.sh every minute (app/tasks/tasks.txt) and an Update starts
# it too; a run that hung (see `pm2 jlist` below) used to be joined by another every minute, and
# none of them ever reached the later steps (ring-push setup, PM2 reload). A run that finds another
# one alive just exits: cron tries again a minute later, and waiting would only queue up copies
# that all start together. The pid file is created with noclobber so two runs can't both take it.
# A pid file rather than flock: PM2 daemons started from this script would inherit a flock
# descriptor and hold the lock for good.
JOBS_PIDFILE="/run/ringq-jobs.pid"
jobs_running() {
    local pid
    pid=$(cat "$JOBS_PIDFILE" 2>/dev/null) || return 1
    [ -n "$pid" ] && [ "$pid" != "$$" ] && kill -0 "$pid" 2>/dev/null && \
        ps -p "$pid" -o args= 2>/dev/null | grep -q "app/scripts/jobs.sh"
}
jobs_take_lock() { ( set -o noclobber; echo $$ > "$JOBS_PIDFILE" ) 2>/dev/null; }
# A run older than this is stuck, not busy: the longest Update takes minutes. On Skyrock a
# `pm2 restart` started at midnight never returned, and for two days every later run skipped,
# so an Update's restart_jobs block (and its PM2 reload) never ran and the new node code
# stayed on disk unloaded. Stop such a run and take over instead of skipping forever.
JOBS_STALE_SECS=7200
if ! jobs_take_lock; then
    if jobs_running; then
        JOBS_OLD_PID=$(cat "$JOBS_PIDFILE" 2>/dev/null || true)
        JOBS_OLD_AGE=$(ps -p "$JOBS_OLD_PID" -o etimes= 2>/dev/null | tr -d ' ' || true)
        if [ -z "$JOBS_OLD_AGE" ] || [ "$JOBS_OLD_AGE" -lt "$JOBS_STALE_SECS" ]; then
            echo "jobs.sh is already running (pid $JOBS_OLD_PID); skipping this run."
            exit 0
        fi
        # Its direct children are what hangs (a pm2 client); daemons they started live in
        # their own session and are left alone.
        echo "jobs.sh pid $JOBS_OLD_PID has run for ${JOBS_OLD_AGE}s; stopping it and taking over."
        pkill -TERM -P "$JOBS_OLD_PID" 2>/dev/null || true
        kill -TERM "$JOBS_OLD_PID" 2>/dev/null || true
        sleep 2
        pkill -KILL -P "$JOBS_OLD_PID" 2>/dev/null || true
        kill -KILL "$JOBS_OLD_PID" 2>/dev/null || true
    fi
    # The pid file is left over from a run that died: take it over once.
    rm -f "$JOBS_PIDFILE"
    jobs_take_lock || exit 0
fi
trap '[ "$(cat "$JOBS_PIDFILE" 2>/dev/null)" = "$$" ] && rm -f "$JOBS_PIDFILE"' EXIT

