-- Qontak CRM integration -- PostgreSQL (database: ringq)
-- Additive only: creates three NEW tables. Touches no existing table or data.
-- Safe to run more than once (IF NOT EXISTS everywhere).
-- Run as the DB owner:  psql -U <owner> -d ringq -v ON_ERROR_STOP=1 -f 2026_10_14_qontak_crm.sql
-- Roll back:            see 2026_10_14_qontak_crm_rollback.sql

BEGIN;

-- One row per tenant. The client secret is AES-256-GCM encrypted by the app
-- (key file /etc/ringq/qontak.key, never in the DB or code). Mekari HMAC auth
-- has no access/refresh tokens, so no token columns are needed.
CREATE TABLE IF NOT EXISTS public.q_qontak_config (
    domain_uuid        uuid PRIMARY KEY,
    enabled            boolean      NOT NULL DEFAULT false,
    environment        varchar(16)  NOT NULL DEFAULT 'production'
                       CHECK (environment IN ('production', 'sandbox')),
    client_id          varchar(128) NOT NULL,
    client_secret_enc  text         NULL,          -- "v1:" || base64(iv|tag|ciphertext); NULL after disconnect
    crm_user_sso_id    varchar(64)  NULL,          -- X-Crm-User-Sso-Id
    settings           jsonb        NOT NULL DEFAULT '{}'::jsonb,
    sign_mode          varchar(16)  NOT NULL DEFAULT 'path_query',
    task_category_id   bigint       NULL,          -- cached Qontak task category id
    connection_status  varchar(20)  NOT NULL DEFAULT 'not_configured'
                       CHECK (connection_status IN ('not_configured', 'connected', 'error', 'disconnected')),
    last_tested_at     timestamptz  NULL,
    last_sync_at       timestamptz  NULL,
    last_error         varchar(500) NULL,
    webhook_token      varchar(48)  NOT NULL,      -- secret path token for qontak/webhooks/{token}
    link_salt          varchar(32)  NOT NULL,      -- rotating salt; changing it revokes every recording link
    updated_by         varchar(64)  NULL,
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS q_qontak_config_webhook_token_uq ON public.q_qontak_config (webhook_token);

-- One row per dialer call (per tenant). local_call_id is generated by the
-- browser when the call starts; the unique key makes every retried event
-- idempotent and guarantees one Qontak task per call.
CREATE TABLE IF NOT EXISTS public.q_qontak_call_journals (
    journal_uuid        uuid PRIMARY KEY,
    domain_uuid         uuid         NOT NULL,
    local_call_id       varchar(64)  NOT NULL,
    user_uuid           varchar(64)  NULL,
    agent_extension     varchar(32)  NULL,
    agent_name          varchar(120) NULL,
    call_direction      varchar(8)   NOT NULL CHECK (call_direction IN ('inbound', 'outbound')),
    caller_number       varchar(32)  NULL,
    destination_number  varchar(32)  NULL,
    call_status         varchar(12)  NOT NULL DEFAULT 'ringing'
                        CHECK (call_status IN ('ringing', 'answered', 'completed', 'missed', 'rejected', 'busy', 'no_answer', 'failed')),
    started_at          timestamptz  NOT NULL DEFAULT now(),
    answered_at         timestamptz  NULL,
    ended_at            timestamptz  NULL,
    duration            integer      NOT NULL DEFAULT 0,   -- seconds, start -> end
    talk_duration       integer      NOT NULL DEFAULT 0,   -- seconds, answered -> end
    qontak_contact_id   varchar(32)  NULL,
    qontak_task_id      varchar(32)  NULL,                 -- the Qontak "journal" (task) id
    xml_cdr_uuid        uuid         NULL,                 -- q_ringq_cdr row holding the recording
    recording_status    varchar(12)  NOT NULL DEFAULT 'none'
                        CHECK (recording_status IN ('none', 'waiting', 'linked', 'unavailable')),
    transcription       text         NULL,
    summary             text         NULL,
    sentiment           varchar(20)  NULL,
    ai_status           varchar(10)  NULL CHECK (ai_status IN ('disabled', 'pending', 'done', 'failed')),
    sync_status         varchar(10)  NOT NULL DEFAULT 'pending'
                        CHECK (sync_status IN ('pending', 'synced', 'failed', 'skipped')),
    retry_count         integer      NOT NULL DEFAULT 0,
    next_attempt_at     timestamptz  NULL,
    sync_locked_at      timestamptz  NULL,
    synced_at           timestamptz  NULL,
    last_error          varchar(500) NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT q_qontak_call_journals_call_uq UNIQUE (domain_uuid, local_call_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS q_qontak_call_journals_task_uq
    ON public.q_qontak_call_journals (domain_uuid, qontak_task_id) WHERE qontak_task_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_qontak_call_journals_due_idx
    ON public.q_qontak_call_journals (next_attempt_at) WHERE next_attempt_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_qontak_call_journals_started_idx
    ON public.q_qontak_call_journals (domain_uuid, started_at DESC);
CREATE INDEX IF NOT EXISTS q_qontak_call_journals_user_idx
    ON public.q_qontak_call_journals (domain_uuid, user_uuid, started_at DESC);

-- Webhook de-duplication / replay protection (pruned after 7 days by `cli.php qontak prune`).
CREATE TABLE IF NOT EXISTS public.q_qontak_webhook_events (
    domain_uuid  uuid        NOT NULL,
    event_hash   char(64)    NOT NULL,
    event_name   varchar(80) NULL,
    received_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (domain_uuid, event_hash)
);
CREATE INDEX IF NOT EXISTS q_qontak_webhook_events_received_idx ON public.q_qontak_webhook_events (received_at);

COMMIT;
