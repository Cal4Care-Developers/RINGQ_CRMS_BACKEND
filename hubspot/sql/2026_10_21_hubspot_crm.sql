-- HubSpot CRM integration -- PostgreSQL (database: ringq)
-- Additive only: creates two NEW tables. Touches no existing table or data
-- (reads q_ringq_cdr and v_domains at runtime, never alters them).
-- Safe to run more than once (IF NOT EXISTS everywhere).
-- Run as the DB owner:  psql -U <owner> -d ringq -v ON_ERROR_STOP=1 -f 2026_10_21_hubspot_crm.sql
-- Roll back:            2026_10_21_hubspot_crm_rollback.sql

BEGIN;

-- One row per tenant. The private app access token is AES-256-GCM encrypted
-- by the app (key file /etc/ringq/hubspot.key, never in the DB or code).
-- Private app tokens have no refresh token, so no refresh/expiry columns.
CREATE TABLE IF NOT EXISTS public.q_hubspot_config (
    domain_uuid          uuid PRIMARY KEY,
    enabled              boolean      NOT NULL DEFAULT false,
    access_token_enc     text         NULL,          -- "v1:" || base64(iv|tag|ciphertext); NULL after disconnect
    token_last4          varchar(8)   NULL,          -- shown masked to admins ("••••abcd")
    portal_id            bigint       NULL,          -- HubSpot account (hub) id, from account-info
    ui_domain            varchar(64)  NULL,          -- app.hubspot.com / app-eu1.hubspot.com
    account_timezone     varchar(64)  NULL,
    granted_scopes       jsonb        NULL,          -- scopes reported for the token (best effort)
    call_status_options  jsonb        NULL,          -- hs_call_status values this portal offers
    dispositions         jsonb        NULL,          -- {"connected": "<guid>", ...} this portal's call outcomes
    settings             jsonb        NOT NULL DEFAULT '{}'::jsonb,
    connection_status    varchar(20)  NOT NULL DEFAULT 'not_configured'
                         CHECK (connection_status IN ('not_configured', 'connected', 'error', 'disconnected')),
    last_tested_at       timestamptz  NULL,
    last_sync_at         timestamptz  NULL,
    last_error           varchar(500) NULL,
    link_salt            varchar(32)  NOT NULL,      -- rotating salt; changing it revokes every recording link
    updated_by           varchar(64)  NULL,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now()
);

-- One row per dialer call (per tenant). local_call_id is generated by the
-- browser when the call starts; the unique key makes every retried event
-- idempotent, and the partial unique index guarantees one HubSpot call per row.
CREATE TABLE IF NOT EXISTS public.q_hubspot_call_journals (
    journal_uuid           uuid PRIMARY KEY,
    domain_uuid            uuid         NOT NULL,
    local_call_id          varchar(64)  NOT NULL,
    user_uuid              varchar(64)  NULL,
    agent_extension        varchar(32)  NULL,
    agent_name             varchar(120) NULL,
    call_direction         varchar(8)   NOT NULL CHECK (call_direction IN ('inbound', 'outbound')),
    call_origin            varchar(16)  NOT NULL DEFAULT 'dialer' CHECK (call_origin IN ('dialer', 'click_to_call')),
    caller_number          varchar(32)  NULL,
    destination_number     varchar(32)  NULL,
    call_status            varchar(12)  NOT NULL DEFAULT 'ringing'
                           CHECK (call_status IN ('ringing', 'answered', 'completed', 'missed', 'rejected', 'busy', 'no_answer', 'failed')),
    started_at             timestamptz  NOT NULL DEFAULT now(),
    answered_at            timestamptz  NULL,
    ended_at               timestamptz  NULL,
    duration               integer      NOT NULL DEFAULT 0,   -- seconds, start -> end
    talk_duration          integer      NOT NULL DEFAULT 0,   -- seconds, answered -> end (measured by the dialer)
    notes                  text         NULL,                 -- agent notes, written into hs_call_body
    hubspot_contact_id     varchar(32)  NULL,
    associated_contact_id  varchar(32)  NULL,                 -- contact the HubSpot call is actually associated with
    hubspot_call_id        varchar(32)  NULL,                 -- HubSpot call (engagement) object id
    create_attempted_at    timestamptz  NULL,                 -- set before POST /calls: crash recovery searches by call ref
    xml_cdr_uuid           uuid         NULL,                 -- q_ringq_cdr row holding the recording
    recording_status       varchar(12)  NOT NULL DEFAULT 'none'
                           CHECK (recording_status IN ('none', 'waiting', 'linked', 'unavailable')),
    transcription          text         NULL,
    summary                text         NULL,
    sentiment              varchar(20)  NULL,
    ai_status              varchar(10)  NULL CHECK (ai_status IN ('disabled', 'pending', 'done', 'failed')),
    ai_error               varchar(300) NULL,
    sync_status            varchar(10)  NOT NULL DEFAULT 'pending'
                           CHECK (sync_status IN ('pending', 'synced', 'failed', 'skipped')),
    retry_count            integer      NOT NULL DEFAULT 0,
    next_attempt_at        timestamptz  NULL,
    sync_locked_at         timestamptz  NULL,
    synced_at              timestamptz  NULL,
    last_error             varchar(500) NULL,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT q_hubspot_call_journals_call_uq UNIQUE (domain_uuid, local_call_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS q_hubspot_call_journals_hscall_uq
    ON public.q_hubspot_call_journals (domain_uuid, hubspot_call_id) WHERE hubspot_call_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_hubspot_call_journals_due_idx
    ON public.q_hubspot_call_journals (next_attempt_at) WHERE next_attempt_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS q_hubspot_call_journals_started_idx
    ON public.q_hubspot_call_journals (domain_uuid, started_at DESC);
CREATE INDEX IF NOT EXISTS q_hubspot_call_journals_user_idx
    ON public.q_hubspot_call_journals (domain_uuid, user_uuid, started_at DESC);
CREATE INDEX IF NOT EXISTS q_hubspot_call_journals_contact_idx
    ON public.q_hubspot_call_journals (domain_uuid, hubspot_contact_id, started_at DESC) WHERE hubspot_contact_id IS NOT NULL;

COMMIT;
